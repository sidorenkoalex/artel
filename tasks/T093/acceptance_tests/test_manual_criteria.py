# AC-4: manual — «diff не удаляет и не смягчает ни одного существующего
# правила, теста, гейта, лимита или guard-проверки... каждая правка
# skills/ или templates/ — новый абзац/пункт либо замена формулировки об
# устаревшей механике на актуальную» — сверка СМЫСЛА прозы, не синтаксиса
# диффа: легитимная замена устаревшей формулировки на актуальную тоже
# удаляет старые строки unified diff, поэтому счёт удалённых/добавленных
# строк не отличает смягчение от честной правки. Это ровно тот случай,
# что test-authoring называет валидной причиной manual — «человеческий
# вердикт по существу»: reviewer/Оператор читает диффы skills/ и
# templates/ на review_gate и приёмке и судит, смягчает ли новая
# формулировка старую дисциплину. Тот же приём, что AC-6 в
# tasks/T037/acceptance_tests/test_manual_criteria.py («правило проверяет
# ревьювер по диффу»).

# AC-6: skip — «Полный набор tests/ зелёный» уже исполняется штатным CI
# (.github/workflows/ci.yml, шаг `unittest discover -s tests -v`) на
# каждом коммите ветки и требуется автогейтом acceptance
# (orchestrator/fsm.py::_autogate_conditions, run_full_suite) для
# перехода в merge_gate — тем же основанием и той же формулировкой
# критерия, что AC-4 в
# tasks/T046/acceptance_tests/test_predlozheniya_sisteme.py и AC-8 в
# tasks/T072/acceptance_tests/test_manual_criteria.py. Дублирующий
# subprocess-прогон здесь не даёт новой гарантии сверх штатных гейтов —
# автогейт acceptance для T093 в любом случае отключён наличием AC-4
# (manual), так что повторный прогон тут только удлиняет приёмку задачи.
