# AC-2: escalate — SPEC (требование 2 и сам AC-2) вводит НОВУЮ CLI-команду
# пульта, но нигде не называет её имя, аргументы или Python-точку входа —
# в отличие от прецедента tasks/T070/SPEC.md, где новая команда `pause
# <id>`/`resume <id>` названа буквально в заголовке и в тексте требования
# 1/3. Без имени команды и её сигнатуры тест не может ни вызвать её
# напрямую (`fsm.cmd_<???>`), ни через `artel.py <???> ...` (dispatch-
# таблица `orchestrator/artel.py:209-236`) — любое конкретное имя,
# выбранное здесь, было бы решением о ДИЗАЙНЕ команды, которое SPEC явно
# не зафиксировал, а PLAN.md (где такое решение принимает разработчик)
# на момент tests_writing ещё не существует (skills/test-authoring.md:
# «test_author работает раньше PLAN.md»). Формулировка критерия сама не
# позволяет написать тест без домысливания интерфейса — не «трудоёмко»,
# а структурно недостижимо в границах роли test_author.
#
# Вопрос Оператору: как назвать CLI-команду и её сигнатуру для создания
# ANSWER-n.md? Варианты:
#   A) `answer <id> <файл>` — текст ответа читается из файла (по образцу
#      `new "<title>" --tz <файл>` / `catalog.cmd_new(title, tz_path=...)`,
#      `orchestrator/artel.py:196-199`, `orchestrator/catalog.py:119-123`);
#   B) `answer <id> "<текст>"` — текст ответа прямым аргументом (по
#      образцу `reject <id> "<причина>"` / `fsm.cmd_reject(task_id,
#      reason, ...)`, `orchestrator/fsm.py:1155-1159`);
#   C) обе формы сразу (текст файлом ИЛИ вводом — буквально формулировка
#      TZ.md «CLI-команда для Оператора (например `answer <id>
#      <файл-с-текстом>` или ввод текстом)»), с явным флагом (`--file`)
#      отличающим их.
# Дефолт при молчании Оператора: вариант C — команда `answer`, функция
# `orchestrator.fsm.cmd_answer(task_id: str, text: str, session_id:
# str | None = None) -> None` (сигнатура и модуль по образцу
# `cmd_reject`/`cmd_approve` — гейт возврата, который AC-3/AC-4 этой же
# задачи добавляют, живёт в `fsm.py`, логично держать создание ANSWER-n.md
# рядом), CLI-обвязка `artel.py answer <id> [--file <путь>] [текст...]`
# резолвит текст ДО вызова `cmd_answer` (по образцу `_tz_arg`/
# `catalog.cmd_new`).
