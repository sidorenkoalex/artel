"""AC-4 (tasks/T087/SPEC.md): общий потолок цикла ожидания — конфиг-
константа порядка 60 минут, отсчитываемая от ПЕРВОГО пуша этого вызова
`approve`; повторная подтяжка по AC-6 НЕ сбрасывает этот отсчёт.

Источник — tasks/T087/SPEC.md, «Критерии приёмки», AC-4.

Различить «отсчёт от первого пуша» и «отсчёт сбрасывается повторным
пушем» блокирующим (~час) реальным ожиданием или наивным подсчётом
итераций нельзя — ни SPEC, ни реализация (её ещё нет) не называют
значение потолка, а без него нельзя заранее вычислить, сколько
итераций понадобится, чтобы отличить «не сброшен» от «сброшен» (при
любом фиксированном числе итераций для широкого правдоподобного
диапазона потолка/паузы либо обе гипотезы уложатся в него, либо ни
одна). Вместо подбора числа используется прямой контроль часов
(`time.monotonic`, то же предположение о реализации, что и в остальных
файлах этой задачи — см. докстринг `_sandbox.py`): часы отдают МАЛЫЕ
значения, пока не наступил семантический момент «повторная подтяжка
AC-6 только что случилась» (второй коммит main внедряется ПОБОЧНЫМ
ЭФФЕКТОМ ровно в этот момент — второй ответ `ci.branch_status`,
завершающий первый цикл ожидания), после чего ВСЕ дальнейшие показания
часов — один и тот же ОГРОМНЫЙ момент времени (с исчезающе малым
дрейфом, чтобы не нарушать монотонность).

После скачка часы ЗАМИРАЮТ на одном и том же значении (не дрейфуют —
первая версия этого файла давала пост-скачковым показаниям ползти на
исчезающе малый шаг за вызов, и это оказалось НЕ различимо: при
достаточном числе дешёвых итераций — sleep заглушён, реальных секунд
не проходит — даже сброшенный отсчёт рано или поздно накопил бы ту же
разницу и тоже сработал бы, просто на MAX_ITERATIONS итераций позже —
контрольный прогон с намеренно внесённым сбросом это и показал: тест
ошибочно зеленел). Замороженные часы делают исходы различимыми РОВНО
одной итерацией, а не числом итераций:
- отсчёт от ПЕРВОГО пуша (правильно) — замороженное (огромное)
  показание часов минус ссылка первого пуша (малое значение, снятое ДО
  скачка) — разница огромна с САМОЙ ПЕРВОЙ пост-скачковой проверки —
  `approve` обязан отказать «статус CI неизвестен» почти сразу же.
- отсчёт от ВТОРОГО пуша (сброшен, дефект) — ссылка второго пуша сама
  снята УЖЕ ПОСЛЕ скачка (то же замороженное значение) — разница с
  ЛЮБОЙ последующей проверкой (тоже то же замороженное значение) — РОВНО
  ноль НАВСЕГДА — потолок никогда не сработает сам; `MAX_ITERATIONS`
  ниже — не предмет критерия, а защитный потолок теста, превращающий
  эту гипотетическую бесконечность в явный, быстрый провал теста вместо
  зависания.

Красен до реализации: сегодня цикла ожидания и повторной подтяжки
внутри одного вызова `approve` нет вовсе — после ПЕРВОЙ подтяжки
`approve` останавливается сразу, `ci.branch_status` не вызывается в
этом вызове (`orchestrator/fsm.py`); ни отказ «неизвестен», ни `done`
не наступают — тест ловит это как `state()` остаётся `merge_gate` без
`SystemExit` с нужным текстом (см. первый assert ниже).
"""
import sys
import time
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from _sandbox import GREEN, MergeGateCiWaitTest, RUNNING  # noqa: E402

BIG = 10_000_000.0
# Только защитный потолок теста (не предмет критерия) — см. докстринг:
# при сброшенном отсчёте потолок не сработает НИКОГДА (замороженные
# часы), и без этой границы тест завис бы, а не провалился.
MAX_ITERATIONS = 500


class Ac4CeilingNotResetByRepullTest(MergeGateCiWaitTest):

    def setUp(self):
        super().setUp()
        self.enter_merge_gate()

        self.jump = {"jumped": False, "n": 0}

        def fake_monotonic():
            self.jump["n"] += 1
            if self.jump["jumped"]:
                return BIG  # заморожено — см. докстринг модуля
            return float(self.jump["n"])

        patcher = mock.patch.object(time, "monotonic", fake_monotonic)
        patcher.start()
        self.addCleanup(patcher.stop)

    def test_ac4_deadline_survives_the_ac6_repull_and_still_expires(self):
        self.add_main_commit()

        # index 0: "идёт" — первый цикл жив, часы ещё малые (elapsed
        #   от первого пуша — исчезающе мал, потолок не сработает).
        # index 1: "зелёный", завершающий первый цикл — ПОБОЧНЫМ
        #   ЭФФЕКТОМ здесь же случается второй уход main вперёд (AC-6)
        #   и часы переключаются на "огромные" (замороженные) показания.
        # index 2+: "идёт" (клэмп последнего элемента) — второй цикл
        #   ожидания: именно здесь должен сработать (или НИКОГДА не
        #   сработать) потолок, в зависимости от того, от какой ссылки
        #   он отсчитан.
        sequence = [RUNNING, GREEN, RUNNING]

        def sequenced(branch):
            idx = min(self.calls["n"], len(sequence) - 1)
            resp = sequence[idx]
            self.calls["n"] += 1
            if idx == 1:
                self.add_main_commit(
                    "main-progress-2.txt", "второй прогресс main\n")
                self.jump["jumped"] = True
            if self.calls["n"] > MAX_ITERATIONS:
                self.fail(
                    f"AC-4: потолок ожидания не сработал за "
                    f"{MAX_ITERATIONS} итераций ПОСЛЕ скачка часов — "
                    f"похоже, отсчёт отсчитывается от ВТОРОГО пуша "
                    f"(повторной подтяжки AC-6), а не от первого, как "
                    f"того требует AC-4")
            return resp

        self.calls = {"n": 0}
        self.patch_branch_status(sequenced)

        with self.assertRaises(SystemExit) as exit_:
            self.approve()

        self.assertIn(
            "неизвестен", str(exit_.exception).lower(),
            f"AC-4: потолок ожидания, отсчитанный от ПЕРВОГО пуша, "
            f"обязан сработать после скачка часов, случившегося во "
            f"время повторной подтяжки AC-6 — вместо этого approve "
            f"либо не отказал вовсе, либо отказал другим сообщением: "
            f"{exit_.exception!r}")
        self.assertEqual(
            self.state(), "merge_gate",
            "AC-4: истечение (не сброшенного повторной подтяжкой) "
            "потолка обязано оставить задачу на гейте merge_gate")


if __name__ == "__main__":
    import unittest
    unittest.main()
