class Ac2DocstringMentionNotFlaggedTest(AcMarkerIndentSandbox):

    def test_ac2_docstring_mention_of_marker_syntax_does_not_block_transition(self):
        """Строка `# AC-2: manual` внутри тройных кавычек докстринга
        модуля (пример синтаксиса, не настоящая пометка) не блокирует
        переход `tests_writing -> in_dev`: единственная настоящая
        пометка в файле — `# AC-1: manual` в начале строки, и её
        достаточно для полной трассируемости.

        Ловит мутацию: детекция отступа реализована по тексту без учёта
        строковых литералов/докстрингов (например, простым построчным
        regex `^\\s+#\\s*AC-\\d+:` без исключения диапазона строк
        докстринга/строки) — тогда строка примера внутри докстринга
        читается как настоящий индентированный маркер, переход
        отказывает текстом «с отступом», и `self.state()` остаётся
        `tests_writing` вместо ожидаемого `in_dev`.
        """
        self.enter_tests_writing(SPEC_ONE_AC)
        self.write_acceptance_tests(DOCSTRING_MENTION_TEST,
                                    name="test_placeholder.py")

        out = self.capture(fsm.cmd_advance, self.TASK)

        self.assertEqual(
            self.state(), "in_dev",
            f"упоминание маркера внутри докстринга не обязано блокировать "
            f"переход; вывод guard: {out!r}")
        self.assertNotIn("с отступом", out)


