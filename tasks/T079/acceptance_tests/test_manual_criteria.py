# AC-1: manual — Draft MR заводится через GitHub-адаптер на первом входе
# в in_dev и не дублируется на повторных входах; механизм (заголовок,
# способ различить «первый вход» от «повторного» — БД-флаг или запрос
# к GitHub) SPEC не специфицирует (требование 1) — см. докстринг модуля.
# Оператор проверяет на приёмке: ветка задачи имеет ровно один MR на
# github.com/sidorenkoalex/artel на всём жизненном цикле, даже после
# итераций ревью/reject из verifying.

# AC-2: manual — тот же довод: снятие Draft (undraft) на входе в
# merge_gate — внешний вызов к GitHub без существующего сегодня
# интерфейса в коде. Оператор проверяет на приёмке: MR перестаёт быть
# Draft ровно на переходе acceptance -> merge_gate, не раньше и не позже.

# AC-3: manual — критерий условный по своей формулировке («если
# реализация явно закрывает/помечает MR смерженным») и явно оставляет
# способ реализации открытым (требование 3, ANSWER-1); наблюдаемый
# эффект — состояние реального MR на GitHub после реального push,
# внешняя интеграция без тестового контура. Оператор проверяет на
# приёмке: MR отражает merged-статус после успешного approve из
# merge_gate и НЕ отражает его при любом из трёх отказных исходов
# approve (SPEC T052).

# AC-13: manual — «существующее поведение SPEC T052/T053 не меняется,
# соответствующие тесты остаются зелёными» уже исполняется штатным
# CI-гейтом (.github/workflows/ci.yml, джоб «python»: `unittest discover
# -s tests -v` на каждый пуш ветки) и требуется `merge_gate`
# (orchestrator/fsm.py, cmd_approve при state == "merge_gate") — тот же
# довод, что и tasks/T069/acceptance_tests/test_manual_criteria.py (AC-4
