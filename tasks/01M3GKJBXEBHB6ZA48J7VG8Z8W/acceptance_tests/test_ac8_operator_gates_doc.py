"""AC-8 — 01M3GKJBXEBHB6ZA48J7VG8Z8W: `docs/operator-gates.md` о формате
строки мандата, проверке при записи и шаге `approve`.

Источник — SPEC.md, «Критерии приёмки»:

AC-8. `docs/operator-gates.md` несёт формат строки мандата (только пути
через запятую, пояснения — отдельным абзацем), описание проверки при
записи и шаг `approve` после ответа в `escalated`.

Все три предмета ищутся в разделе «Гейт эскалации (`escalated`)» — том, что
«Материалы» SPEC называют разделом под правку, и том, который Оператор
читает, когда задача уже стоит в эскалации. То же правило, спрятанное в
другой раздел, ответа на гейте не даёт.

Формулировок критерий не фиксирует, поэтому планка ищет не фразы, а
признаки, без которых предмет в тексте отсутствует:

- формат: слова «поясн…» и «абзац» — правило «пояснения отдельным абзацем»
  иначе не выразить;
- проверка при записи: назван её момент («при записи»/«до коммита»/…),
  иначе Оператор продолжит ждать ошибку от гейта, а не от команды;
- шаг `approve`: есть ПРЕДЛОЖЕНИЕ, где `approve` стоит рядом либо с самой
  командой `answer`, либо со снятием эскалации. Гранулярность —
  предложение, а не абзац: весь нумерованный список раздела — один абзац,
  и «оба слова где-то в нём» выполнено уже сегодня, ничего не описывая.

Читается файл рабочей копии — `docs/operator-gates.md` это документация
пульта, не артефакт задачи: артефакты (`SPEC.md`/`PLAN.md`/`REVIEW.md`)
планка с диска не читает вовсе.

Красен до реализации: раздел «Гейт эскалации» (`docs/operator-gates.md:143-185`)
называет оба маркера мандата, но ни слова не говорит ни о том, что элементом
может быть только путь (а пояснение — отдельным абзацем), ни о проверке при
записи, ни о том, что после `answer` в `escalated` эскалацию снимает
`approve`: ни одно предложение раздела не ставит `approve` рядом ни с
командой `answer`, ни со снятием эскалации.
"""
import re
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

import _sandbox  # noqa: E402

DOC = _sandbox.REPO_ROOT / "docs" / "operator-gates.md"

#: Заголовок раздела под правку («Материалы» SPEC).
SECTION = "Гейт эскалации"

#: Момент проверки: критерий требует описать проверку ПРИ ЗАПИСИ.
WRITE_TIME_WORDS = ("при записи", "до коммита", "перед коммитом",
                    "при создании")

#: Что должно стоять в одном предложении с `approve`: имя самой команды
#: (регистрозависимо — «ответ» сюда не годится, речь о шаге конвейера) либо
#: снятие эскалации.
NEXT_STEP_COMPANIONS = ("answer", "снятие эскалации", "снимает эскалацию",
                        "снимающ")

#: Границы предложений: точка/точка с запятой/двоеточие и пробел. Текст
#: раздела перенесён по ~72 символам, поэтому переносы строк сначала
#: разворачиваются в пробелы — иначе «предложением» оказалась бы строка.
SENTENCE_SPLIT = re.compile(r"(?<=[.;:!?])\s+")


def doc_section(text: str, heading_prefix: str) -> str:
    """Тело раздела `##`, чей заголовок начинается с `heading_prefix` — до
    следующего заголовка того же уровня. Пустая строка — раздела нет."""
    lines = text.splitlines()
    start = None
    for i, line in enumerate(lines):
        if line.startswith("## ") and line[3:].startswith(heading_prefix):
            start = i + 1
            break
    if start is None:
        return ""
    body = []
    for line in lines[start:]:
        if line.startswith("## "):
            break
        body.append(line)
    return "\n".join(body)


def sentences(body: str) -> list:
    """Предложения текста: переносы строк развёрнуты в пробелы, деление —
    по точке/точке с запятой/двоеточию."""
    unwrapped = " ".join(line.strip() for line in body.splitlines())
    return [s.strip() for s in SENTENCE_SPLIT.split(unwrapped) if s.strip()]


class OperatorGatesDocTest(unittest.TestCase):

    def section(self) -> str:
        text = DOC.read_text(encoding="utf-8")
        body = doc_section(text, SECTION)
        self.assertTrue(body.strip(),
                        f"в docs/operator-gates.md нет раздела «{SECTION}»")
        return body

    def test_ac8_doc_states_the_mandate_line_format(self):
        """Раздел гейта эскалации говорит, что в строке мандата — только
        пути через запятую, а пояснения идут отдельным абзацем.

        Ловит мутацию: правка документации ограничилась упоминанием новой
        проверки («answer теперь отказывает»), не сказав, КАК писать строку
        — Оператор, получив отказ, снова не знает, что пояснение надо
        вынести из элемента, и правит мандат наугад.
        """
        body = self.section()

        self.assertIn("поясн", body.lower(),
                      "раздел не говорит о пояснениях в строке мандата")
        self.assertIn("абзац", body.lower(),
                      "раздел не говорит, что пояснения идут отдельным "
                      "абзацем")

    def test_ac8_doc_describes_the_check_at_write_time(self):
        """Раздел говорит, что строка мандата проверяется при записи ответа,
        а не только на гейте.

        Ловит мутацию: документация описывает новую проверку как поведение
        гейта («гейт зон отказывает на неизвестном пути») — Оператор
        по-прежнему ждёт, что ошибку в мандате покажет переход, и не
        связывает отказ команды `answer` со своей строкой.
        """
        body = self.section().lower()

        self.assertTrue(
            any(word in body for word in WRITE_TIME_WORDS),
            "раздел не называет момент проверки строки мандата "
            f"({' / '.join(WRITE_TIME_WORDS)})")

    def test_ac8_doc_names_approve_as_the_step_after_the_answer(self):
        """В разделе есть предложение, где `approve` стоит рядом с самой
        командой `answer` либо со снятием эскалации — шаг после ответа.

        Ловит мутацию: `approve` остался только во вводной строке раздела
        («До `approve` ...») и в пункте «`approve` без ответа возвращает роль
        в тот же тупик», не связанных с командой `answer` — Оператор,
        ответивший на эскалацию, снова не знает, что задача стоит и ждёт
        отдельной команды, и цикл `auto` стоит вместе с ней.
        """
        found = [s for s in sentences(self.section())
                 if "approve" in s
                 and any(word in s for word in NEXT_STEP_COMPANIONS)]

        self.assertTrue(
            found,
            "ни одно предложение раздела не ставит approve рядом с командой "
            "answer или со снятием эскалации: "
            + repr([s for s in sentences(self.section()) if "approve" in s]))


if __name__ == "__main__":
    unittest.main()
