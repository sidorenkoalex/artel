"""AC-5 (tasks/T095/SPEC.md): при варианте 4а (ленивый расчёт при
генерации report) лог шага, недоступный на момент расчёта (вычищен
`prune` или отсутствует), пропускается по этому шагу честно — без
ошибки и без падения генерации `report`.

Наблюдаемое поведение здесь варианто-независимо (см. докстринг
`test_ac2_aggregation_task_and_corpus.py`): задача существует в
`state.db`, но соответствующего файла `.artel/logs/<id>-<role>-N.log`
на диске нет (ни разу не было — тот же наблюдаемый случай, что и
«вычищен `prune`», см. `orchestrator/prune.py`, требование про удаление
файлов логов). При варианте 4б это же отсутствие файла означает, что
журнальной записи метрики тоже никогда не появилось (её нечем было
посчитать) — то же самое «честно пропущено», не «отчёт упал».

Зелёный с рождения: без метрики трения в `report` попросту нечему
упасть на отсутствующем логе — `cmd_report()` уже существует (T092) и
уже не падает на задаче без единого шага. Тест начинает осмысленно
охранять поведение ровно тогда, когда реализация добавит чтение файлов
логов, — до этого момента он корректно зелёный, а не красный «по
неправильной причине»: он не проверяет ничего специфичного для метрики
трения, кроме самого факта отсутствия падения.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from _sandbox import FrictionSandboxTest  # noqa: E402


class MissingLogHonestSkipTest(FrictionSandboxTest):

    def test_ac5_report_does_not_fail_when_step_log_is_absent(self):
        self.mk_task("T001", "Задача без доступного лога шага (prune)")
        # config.LOGS остаётся пустым — ни одного файла лога для T001

        try:
            html = self.run_report_html()
        except Exception as exc:  # noqa: BLE001 — сам факт исключения = дефект
            self.fail(f"report упал на отсутствующем логе шага: {exc!r}")

        self.assertIn("T001", html,
                      "задача пропала из отчёта целиком вместо честного "
                      "пропуска одной лишь метрики трения по её шагу")


if __name__ == "__main__":
    unittest.main()
