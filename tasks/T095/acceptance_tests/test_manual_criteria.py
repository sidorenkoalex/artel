# AC-7: manual — «PLAN задачи фиксирует, какой из двух способов (4а или
# 4б) выбран, и обоснование выбора с учётом retention логов» — содержимое
# конкретного артефакта PLAN.md конкретного разработчика, которого на
# момент написания этих тестов ещё не существует (test_author работает
# раньше PLAN.md, skills/test-authoring.md) — тот же случай, что уже
# решён прецедентом `tasks/T058/acceptance_tests/test_manual_criteria.py`
# (AC-5 там) и `tasks/T062/acceptance_tests/
# test_ac6_ac7_ac8_manual_criteria.py` (AC-6 там): факт и полнота записи
# в ещё не написанном документе сверяет Оператор чтением PLAN.md на
# приёмке. Часть этого же критерия, не зависящая от текста PLAN.md —
# что выбранный способ вообще ограничен зонами agent_log.py/report.py
# (+точка завершения шага при 4б) и не трогает защищённые системы —
# тестируется напрямую в `test_ac6_ac8_protected_zones.py`.

# AC-11: manual — «формат логов stream-json (что и как пишет CLI агента)
# не меняется — расширяется только разбор существующего формата». Речь о
# формате, который пишет ВНЕШНИЙ CLI агента (Claude Code, вызывается
# `orchestrator/runner.py`, вне зоны этой задачи, AC-8) — этот репозиторий
# им не управляет и в принципе не может «поменять» его со своей стороны;
# наблюдаемая часть критерия внутри зоны задачи — что уже существующее
# поведение записи/рендера лога шага (`agent_log.render_agent_line`,
# `agent_log.tee_lines`, `agent_log.OutputPump`) не подверглось правке —
# уже покрыта характеризующими тестами-прецедентами `tests/
# test_agent_log.py` (конкретные входы/выходы rendere/pump на реальных
# событиях stream-json) и требованием AC-12 «остаться зелёным» — то же
# рассуждение, что и для AC-9/AC-10 в отношении диффа: дублирующий
# пересказ здесь не даёт новой гарантии сверх существующего
# характеризующего набора и рискует ложным red/green на другой машине
# (тот же приём, что `tasks/T037/acceptance_tests/test_manual_criteria.py`).

