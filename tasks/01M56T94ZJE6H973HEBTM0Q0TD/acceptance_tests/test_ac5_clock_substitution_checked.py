"""AC-5: подмена часов, которую `Popen.wait` не опрашивает, краснит метод предела `suite-run`.

Группа: разовый
Красен до реализации: подмены часов в методе сегодня нет и проверять ему нечего — когда `Popen.wait` обрывает прогон по реальному времени, не читая `subprocess._time`, метод зелёный, а планка ждёт красного.

Метод гоняется вложенным pytest; прослойка под подменой часов теста
(`_meta.py`, режим `noclock`) заменяет настоящий `Popen.wait` прогона ветки
из `_run_full_suite_to_log` реализацией, не опрашивающей подменённый
источник времени: она ждёт старта всех тестов прогона по настоящим
`time.monotonic` и бросает `TimeoutExpired` через 0,5 с. Отчёт о
таймауте при этом верен и короток — зелёным по реальному времени метод
остаться может, если сам не проверяет, что подмена сработала.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _meta import run_limit_test  # noqa: E402


class ClockSubstitutionCheckedTest(unittest.TestCase):

    def test_ac5_wait_not_polling_substituted_clock_reddens_method(self):
        """`Popen.wait` не опрашивает подменённые часы — метод предела красен проваленным утверждением.

        Сценарий: режим `noclock`; прослойка оборвала прогон ветки сама
        (событие `noclock_cut`) после старта пробника, не прочитав ни разу
        `subprocess._time`; отчёт «не уложился в N», без 60. Метод обязан
        покраснеть провалом утверждения (исход `failed`, не ошибка сбора и
        не потолок вызова): подмена часов не действовала.

        Ловит мутацию: в методе нет проверки, что подмена часов копии
        сработала (часы опрошены прогоном pytest и переведены), — обрыв
        чужими средствами за полсекунды даёт верный отчёт, и метод
        зелёный.
        """
        run = run_limit_test("noclock")
        self.assertTrue(run.of("noclock_cut"),
                        "прослойка не оборвала прогон ветки — возмущение не "
                        "применено\n" + run.context())
        self.assertEqual(run.outcome, "failed", run.context())


if __name__ == "__main__":
    unittest.main()
