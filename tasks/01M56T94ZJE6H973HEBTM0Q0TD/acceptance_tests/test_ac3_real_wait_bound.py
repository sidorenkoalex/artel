"""AC-3: обрыв по реальному отсчёту предела N краснит метод предела `suite-run`.

Группа: разовый
Красен до реализации: метод сегодня сам ждёт предел N (11–13 с) по реальным часам и реального ожидания не мерит — с обрывом, возвращённым к реальному отсчёту, он зелёный, а планка ждёт красного.

Метод гоняется вложенным pytest; прослойка под подменой часов теста
(`_meta.py`, режим `realtime`) возвращает обрыв прогона ветки к реальному
отсчёту: внутренний `Popen._wait` из `_run_full_suite_to_log` сначала
ждёт предел по настоящему `time.monotonic` и лишь затем зовёт настоящий
`_wait` — часы подмены теста по-прежнему опрашиваются, отчёт о таймауте
верен, длинным становится только реальное ожидание обрыва.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _meta import run_limit_test  # noqa: E402


class RealWaitBoundTest(unittest.TestCase):

    def test_ac3_cut_after_real_limit_seconds_reddens_method(self):
        """Обрыв, ждущий N реальных секунд, — метод предела красен, а не зелёный по реальным часам.

        Сценарий: режим `realtime`; прослойка дождалась предела N по
        реальным часам (событие `realtime_elapsed`), затем настоящий
        `Popen._wait` оборвал прогон ветки (событие `cut_by_real_wait`) —
        отчёт «не уложился в N» тот же, что без возмущения. Метод обязан
        покраснеть: реальное ожидание, от которого зависит исход, — N ≥ 11 с
        при пороге 5 с, измеренном `time.monotonic`.

        Ловит мутацию: в методе нет замера реального ожидания обрыва через
        `time.monotonic` (или порог выше N, или замерен интервал, не
        включающий ожидание обрыва) — метод зелёный через N реальных секунд.
        """
        run = run_limit_test("realtime")
        self.assertTrue(run.of("realtime_elapsed"),
                        "прослойка не дождалась реального предела — "
                        "возмущение не применено\n" + run.context())
        self.assertTrue(run.of("cut_by_real_wait"),
                        "обрыва настоящим Popen._wait нет — краснота была "
                        "бы не от реального ожидания\n" + run.context())
        self.assertEqual(run.outcome, "failed", run.context())


if __name__ == "__main__":
    unittest.main()
