"""AC-8: полный прогон `tests/` на карте из AC-7 зелёный, и PLAN несёт
число тестов, падавших на этой карте до правки.

Критерий распадается на две половины с РАЗНОЙ проверяемостью, и планка
обходится с ними по-разному.

Вторая половина — число в PLAN.md — проверяется тестом ниже.

Первая половина — сам полный прогон — в планку не помещается физически, и
это измерено, а не предположено (27.09, эта же машина):

- последовательный прогон `tests/` в копии дерева кода — около 280 с
  (замер: 30 файлов из 186, взятых через один, дают 46 с);
- тот же прогон, разложенный на 12 одновременных подпроцессов, — 200 с
  (параллелизм тут почти не помогает: тесты сами спавнят подпроцессы и
  упираются не в процессор);
- потолок ОТДЕЛЬНОГО теста планки — `stack.PER_TEST_TIMEOUT_SEC` = 120 с,
  потолок ВСЕГО прогона планки — `config.ACCEPTANCE_TIMEOUT_SEC` = 300 с;
- сверх того в копии дерева без `.git` падает
  `tests/test_liveness.py::TerminateProcessGroupTest` — по причине, к
  карте исполнителей отношения не имеющей.

То есть детерминированный тест первой половины не «трудоёмок», а
невозможен: он не может закончиться внутри отведённого планке времени ни
при каком способе прогона. Отсюда пометка manual ниже — её проверяет
Оператор на приёмке тем же прогоном, которым развёрнутое число и
получено. Существо критерия при этом планкой не брошено: AC-3 и AC-4
прогоняют на подменённых картах всех читателей боевой карты, AC-5 —
`tests/test_analyst_role.py` на провайдере Codex, AC-7 — саму
регрессионную проверку.

Красен до реализации: PLAN.md задачи ещё не создан — числа падавших
тестов неоткуда взять.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

import _util  # noqa: E402

# AC-8: manual — полный прогон tests/ на карте AC-7 не помещается в потолки планки (замер 27.09: 280 с последовательно, 200 с на 12 подпроцессах при PER_TEST_TIMEOUT_SEC=120 и ACCEPTANCE_TIMEOUT_SEC=300); Оператор проверяет прогоном руками, тестом ниже проверено число в PLAN


class PlanNamesFailureCountTest(unittest.TestCase):
    """Число падавших тестов в PLAN.md."""

    def test_ac8_plan_names_how_many_tests_failed_on_that_map(self):
        """PLAN.md несёт строку с числом тестов, падавших на карте AC-7 до
        правки, и это число не ноль.

        Ловит мутацию: разработчик пишет в PLAN «на этой карте падений не
        было» (не прогнав набор на подменённой карте вовсе) — число
        оказывается нулём, хотя раздел «Контекст» SPEC называет
        `tests/test_analyst_role.py` красным на этой карте прямым текстом,
        а AC-5 воспроизводит его падение. Ноль означает, что прогона не
        было либо карта подменена не та, и цена класса в PLAN остаётся
        незаписанной.
        """
        plan = _util.plan_text()
        self.assertIsNotNone(
            plan,
            f"PLAN.md задачи не найден в артефактной ветке "
            f"{_util.artifact_branch.branch_name(_util.TASK_ID)} — число "
            f"падавших тестов пишет роль developer")

        count = _util.plan_failed_count(plan)
        self.assertIsNotNone(
            count,
            f"в PLAN.md нет строки с числом тестов, падавших на карте AC-7 до "
            f"правки\nформа строки: {_util.PLAN_FAILED_COUNT_SHAPE}")
        self.assertGreater(
            count, 0,
            f"PLAN.md называет {count} падавших тестов на карте AC-7 до "
            f"правки, но раздел «Контекст» SPEC называет "
            f"{_util.ANALYST_TEST} красным на этой карте, и AC-5 его "
            f"падение воспроизводит")


if __name__ == "__main__":
    unittest.main()
