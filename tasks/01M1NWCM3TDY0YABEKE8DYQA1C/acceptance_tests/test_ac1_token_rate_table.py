"""AC-1 (SPEC: «Стоимость частичного шага при таймауте: курс токенов
вместо тишины») — «orchestrator/config.py несёт именованную таблицу
курса токенов по идентификатору роли (analyst, test_author, developer,
reviewer)... roles.yaml не изменён.»

Не тест: критерий буквально требует курс на ВСЕ четыре роли, включая
`developer` — а `developer` это ровно та роль, для которой уже
существуют залоченные тесты T040 (`tests/test_step_cost.py:319` и `:634`),
жёстко утверждающие, что таймаут этой роли с usage-событиями НЕ трогает
`spent_usd`. AC-8 этой же SPEC требует эти тесты зелёными без ослабления
и без удаления кейсов. Требование 2 SPEC (безусловный для любой роли с
заданным курсом механизм начисления) делает эти два требования
одновременно неисполнимыми для роли `developer` — подробности и варианты
разрешения в эскалации ниже (общей для AC-1 и AC-2, см. также
`test_ac2_known_rate_partial_charge.py`).

Зелёный с рождения: файл не содержит исполняемых тестовых методов (AC-1
эскалирован маркером ниже вместо теста — сам факт эскалации не проверяем
юнит-тестом, это решение test_author, а не поведение кода задачи),
поэтому `unittest discover` проходит его без сборов что до, что после
появления кода задачи.
"""

# AC-1: escalate — требование 1/AC-1 обязывает завести курс токенов на
# ВСЕ четыре роли конвейера (analyst, test_author, developer, reviewer).
# `developer` — та же роль, для которой существующие залоченные тесты
# T040 (tests/test_step_cost.py:319 ChargeMissingResultTest.
# test_partial_tokens_are_journaled_without_touching_spent и
# tests/test_step_cost.py:634 CmdRunPartialCostTest.
# test_timeout_with_usage_events_charges_a_partial_token_sum) буквально
# утверждают: таймаут с usage-событиями для role="developer" НЕ трогает
# spent_usd (assertEqual(...,0.0)). AC-8 требует эти тесты зелёными без
# ослабления проверок и без удаления кейсов. Если у developer появляется
# реальный курс, требование 2 SPEC (безусловный механизм для ЛЮБОЙ роли с
# заданным курсом) неизбежно засчитает частичную стоимость этой роли в
# spent_usd — оба локнутых теста покраснеют. developer — центральный
# мотивирующий кейс задачи (Контекст SPEC: «канарейка test_author,
# оценка объёма developer»), так что не задать ему курс отводит задачу от
# собственной цели ровно для этого случая. Полный батч вопросов — ниже.
#
# ## Эскалация
#
# ### Вопросы
#
# 1. (блокирует AC-1 целиком) Требование 1 требует курс для developer;
#    AC-8 требует зелёными без ослабления два теста T040, буквально
#    утверждающих обратное для этой роли (см. выше). Как разрешить?
#    - Вариант A: снять лок с этих двух тестов отдельным ADR — курс для
#      developer калибруется наравне с остальными тремя ролями, тесты
#      T040 (tests/test_step_cost.py:319 и :634) переписываются
#      разработчиком под новое поведение (assertGreater вместо
#      assertEqual(...,0.0)) как часть этой задачи.
#    - Вариант B: developer осознанно исключается из таблицы курса
#      требования 1 — AC-1 переформулируется («по идентификатору роли
#      (analyst, test_author, reviewer)», без developer); мотивирующий
#      кейс (таймауты developer) решается только верхней оценкой/алертом
#      требования 3, не точной частичной суммой.
#    - Вариант C: другое — опишите, если ни A, ни B не подходит.
#    - Дефолт при молчании: вариант B (минимальное изменение — тесты
#      T040 остаются как есть байт-в-байт, developer получает только
#      оценку/алерт).
#
# ### Контекст
#
# Сделано: AC-2 (test_ac2_known_rate_partial_charge.py, роль test_author
# — не конфликтует с локнутыми тестами), AC-3 (test_ac3_..., роль
# verifier — курс не задан), AC-4 (test_ac4_..., роль developer,
# сценарий БЕЗ единого usage-события — поведение не меняется, конфликта
# нет), AC-5 (бюджетный гейт spent_usd + spent_estimate_usd), AC-6
# (report), AC-7 (RETRO), AC-9 (миграция БД не пересчитывает прошлые
# задачи) — во всех остальных test_ac*.py этого каталога. AC-8 помечен
# skip (test_ac8_...) — регрессия tests/ уже покрыта штатным CI-гейтом.
#
# ### Блокирует
#
