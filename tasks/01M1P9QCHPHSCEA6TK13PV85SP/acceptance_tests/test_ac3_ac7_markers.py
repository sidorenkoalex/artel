# AC-3: escalate — «PLAN несёт раздел расширения зон с обоснованием,
# подкреплённым ANSWER Оператора с явным согласием на расширение» не
# фиксирует ни одного из трёх параметров, без которых механическую
# проверку не написать:
#   1. Заголовок/формат раздела PLAN.md («## Расширение зон»? отдельное
#      YAML-поле фронтматтера? список путей построчно или через
#      запятую, тем же приёмом, что `zones:` части 1?) — ни SPEC, ни ТЗ
#      этой задачи, ни ТЗ/SPEC родителя (01M1NKVPD2A79PQ6K0JVV1B2Q1,
#      коммит 12e4a906, требование 4/AC-12) не называют формат;
#      прецедента такого раздела в кодовой базе нет (проверено —
#      `grep -rn "расширени" tasks/*/PLAN.md` не находит ни одного
#      случая с похожей структурой).
#   2. Колонку/поле БД, в которое пишется расширение (ТЗ называет
#      только модуль — `orchestrator/store.py` — не имя колонки).
#   3. Что именно код МЕХАНИЧЕСКИ сверяет как «подкреплено ANSWER
#      Оператора с явным согласием» — существование хотя бы одного
#      ANSWER-n.md задачи (по образцу `_answer_baseline_or_refuse`,
#      существование без разбора содержания) или разбор текста ANSWER
#      на предмет конкретной формулировки согласия (семантика,
#      которую код сегодня нигде не разбирает — `orchestrator/answer.py`
#      хранит ответ Оператора как свободный текст, не структуру).
#
# Это не техническая деталь на усмотрение test_author (как формат
# `zones:` части 1, комментарий которого в templates/SPEC.md сам решил
# «через запятую», не будучи зафиксированным ни одним AC) — здесь три
# независимых развилки одновременно образуют новый протокол
# авторизации между тремя артефактами (PLAN/ANSWER/БД), ни одна из
# которых не имеет опоры ни в SPEC/ТЗ этой задачи, ни в существующем
# коде (`grep` по «мандат»/«расширение объёма» не находит ни одного
# места, где такая проверка уже механически реализована — только
# текстовые упоминания практики ручного approve). Тест, зафиксировавший
# один из вариантов без решения Оператора, превратил бы собственное
# изобретение test_author в планку приёмки (`skills/test-authoring.md`,
# «Запрещено»).
#
# Вопрос Оператору: каким конкретно способом код `in_dev -> review`
# распознаёт исключение AC-3?
#   (a) PLAN.md несёт раздел `## Расширение зон` со списком путей
#       (формат — как `zones:` части 1, через запятую) и обоснованием;
#       код проверяет ТОЛЬКО наличие/структуру этого раздела и
#       существование хотя бы одного `ANSWER-n.md` задачи (без разбора
#       текста ANSWER на согласие) — «мандат» проверяется процедурно,
#       тем же доверием, что и текстовая строка «монолит принят
#       Оператором» в SPEC (docs/operator-gates.md, гейт SPEC, п.6).
#   (b) То же самое, но код дополнительно требует, чтобы ANSWER.md
#       содержал конкретную распознаваемую формулировку согласия
#       (например заданный маркер вроде «согласен на расширение зон:
#       <путь>») — какую именно формулировку признавать, тоже нужно
#       решение Оператора.
#   (c) Другой формат раздела PLAN.md/поля БД — Оператор называет свой.
# Дефолт при молчании: вариант (a) — самый дешёвый механически (не
