"""AC-8 (tasks/01M2YWRB9HWW99R57HWGP2M7MQ/SPEC.md): `docs/operator-gates.md`,
раздел «Гейт SPEC», содержит форму команды `reject <id> "<причина>"` и
порядок «`reject` -> `auto` -> аналитик переписывает SPEC -> новый
`approve`», сохраняя редактуру Оператором как законный ход для правок в
одну-две строки.

Проверяется ИМЕННО раздел «Гейт SPEC», не файл целиком: слова `reject`,
`auto` и `approve` встречаются в соседних разделах того же документа, и
проверка по всему файлу была бы зелёной, не будь правки вовсе.

Документ — файл репозитория, не артефакт задачи: он лежит в рабочей копии
и на гейте, и у автора планки, читается с диска штатно (правило «источник
артефактов задачи — только артефактная ветка» касается `SPEC.md`/`PLAN.md`
и прочих `tasks/<id>/`, которых в среде прогона планки нет).

Формулировки сверяются терпимо к редактуре: кавычки в форме команды — любые
из принятых в документе, между звеньями порядка допускается любой текст.
Дословно фиксируются только имена команд и сам порядок — то, что критерий
называет поимённо.

Красен до реализации: раздел «Гейт SPEC» сегодня несёт одну фразу «Отказ
(`reject`) или редактура Оператором: …» без формы команды и без порядка
переделки — ни формы `reject <id> "<причина>"`, ни звена `auto` в разделе
нет.
"""
import re
import sys
import unittest
from pathlib import Path

# Корень рабочего каталога КОДА задачи: планка материализуется на гейте
# именно в него (`acceptance.materialize_from_branch`), и документ ветки
# лежит рядом — `../../../docs/operator-gates.md` от этого файла.
REPO_ROOT = Path(__file__).resolve().parents[3]

DOC_REL = "docs/operator-gates.md"
SECTION_TITLE = "Гейт SPEC"

# Форма команды: `reject <id> "<причина>"` — кавычки любые из ходовых
# (прямые, ёлочки, апострофы), между звеньями допустим пробел/бэктик.
COMMAND_FORM = re.compile(
    r'reject`?\s+`?<id>`?\s+`?["«\'“]<причина>["»\'”]')

# Порядок переделки: reject -> auto -> аналитик переписывает SPEC ->
# новый approve. Между звеньями — любой текст без разрыва абзаца.
ORDER = re.compile(
    r"reject.{0,120}?auto.{0,200}?(аналитик|analyst).{0,200}?approve",
    re.IGNORECASE | re.DOTALL)

# Редактура Оператором остаётся законным ходом — и остаётся привязанной к
# мелкой правке («одну-две строки» в любом написании дефиса/тире).
EDITING_LEGIT = re.compile(r"редактур", re.IGNORECASE)
EDITING_SCOPE = re.compile(r"одн\w*\W{1,3}дв\w*\s+строк", re.IGNORECASE)


def spec_gate_section() -> str:
    """Текст раздела «Гейт SPEC» документа — от его заголовка до
    следующего заголовка того же уровня."""
    text = (REPO_ROOT / DOC_REL).read_text(encoding="utf-8")
    chunks = re.split(r"^## ", text, flags=re.MULTILINE)
    for chunk in chunks:
        if chunk.startswith(SECTION_TITLE):
            return chunk
    raise AssertionError(
        f"в {DOC_REL} нет раздела «{SECTION_TITLE}» — проверять нечего")


class SpecGateSectionDocumentsTheRejectTest(unittest.TestCase):

    def test_ac8_section_carries_the_command_form(self):
        """Оператор, открывший протокол гейта SPEC, видит, ЧТО именно
        набрать: форму команды с id задачи и причиной в кавычках, а не
        одно слово «отказ».

        Ловит мутацию: форма команды дописана в общий раздел «Роль
        ассистента» или в «Гейт merge» (где `reject` уже упоминается), а
        раздел «Гейт SPEC» остался с прежней фразой — регулярка не найдёт
        формы внутри раздела.
        """
        self.assertRegex(spec_gate_section(), COMMAND_FORM)

    def test_ac8_section_carries_the_rework_order(self):
        """Тот же раздел называет порядок целиком: `reject` с причиной,
        затем `auto`, затем аналитик переписывает SPEC, затем новый
        `approve` — Оператор видит, что после отказа задачу надо запустить,
        а не ждать.

        Ловит мутацию: в раздел вписана только команда, без звена `auto`
        («после reject задача возвращается аналитику») — порядок
        оборвётся, и Оператор оставит задачу стоять в `spec_writing`, как
        это и произошло 20.09.
        """
        self.assertRegex(spec_gate_section(), ORDER)

    def test_ac8_operator_editing_stays_a_legitimate_move(self):
        """Правка текста Оператором прямо на гейте остаётся в разделе
        законным ходом и остаётся привязанной к мелкой правке в одну-две
        строки: новый порядок не вытесняет её, а разграничивает с ней.

        Ловит мутацию: абзац про редактуру заменён формой команды целиком
        (переписан «начисто») — упоминание редактуры или её границы
        «одну-две строки» пропадёт из раздела.
        """
        section = spec_gate_section()
        self.assertRegex(section, EDITING_LEGIT)
        self.assertRegex(section, EDITING_SCOPE)


if __name__ == "__main__":
    unittest.main()
