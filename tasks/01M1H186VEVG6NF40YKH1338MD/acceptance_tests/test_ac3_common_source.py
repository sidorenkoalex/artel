# id-format-greplint (bash-шаг GitHub Actions, .github/workflows/ci.yml)
# и Python-кодом перехода (orchestrator/fsm.py/orchestrator/
# fsm_advance.py). Эти два потребителя исполняются в РАЗНЫХ средах — у
# юнит-теста этого репозитория нет тестового контура, который прогоняет
# сам GitHub Actions job (нет локального раннера workflow в песочнице
# unittest, а имитация bash-шага regex-парсингом YAML доказывала бы
# только структуру файла, не фактическое поведение CI при правке
# источника). Нельзя детерминированно исполнить сам bash-шаг CI, чтобы
# пронаблюдать смену его поведения при правке общего источника, — то
# есть само утверждение критерия («правка источника меняет поведение
# ОБЕИХ проверок») непроверяемо в этой среде без запуска настоящего
# GitHub Actions. Оператор проверит на ревью/приёмке, что оба
