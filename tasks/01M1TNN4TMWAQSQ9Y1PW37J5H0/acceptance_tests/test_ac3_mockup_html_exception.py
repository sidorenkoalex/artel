"""AC-3 (SPEC 01M1TNN4TMWAQSQ9Y1PW37J5H0): существующий на `main`
`tasks/T080/mockup.html` — единственный реальный файл первого уровня
`tasks/<id>/`, сегодня отсутствующий в белом списке AC-1 (`*.md`
известных типов, `acceptance_tests/`, `*.patch`). Разработчик фиксирует
решение в PLAN.md — явное исключение с указанием задачи T080, либо
удаление отдельным приложением к PLAN; независимо от выбора, ПОСЛЕ его
применения `guard --all`, прогнанный на настоящем дереве `tasks/`
репозитория, не имеет права назвать этот файл посторонним.

Тест не предполагает, КАКОЕ из двух решений выбрал разработчик — оба
делают наблюдаемое утверждение теста истинным одинаково: явное
исключение оставляет файл на месте, но guard молчит про него; удаление
убирает файл, и guard не может назвать посторонним то, чего физически
нет.

Зелёный с рождения: белого списка первого уровня `tasks/<id>/` в guard.py сегодня нет вовсе, поэтому `mockup.html` не проверяется этим правилом и не помечается — тест фиксирует инвариант на будущее, не тавтологию.

Подробности: белого правила первого уровня `tasks/<id>/` в
guard.py сегодня нет вовсе (SPEC 01M1TNN4TMWAQSQ9Y1PW37J5H0, требования
1-2) — `mockup.html` не проверяется этим правилом уже сегодня, поэтому
`guard --all` не называет его посторонним и сейчас, без всякого решения
AC-3. Это не тавтология: тест фиксирует ИНВАРИАНТ, который обязан
пережить появление правила требования 1/2, — как только оно появится
(эта же SPEC, тот же PLAN.md), `mockup.html` обязан остаться непомеченным
именно ЧЕРЕЗ явное решение AC-3, а не случайно. Провалидировано стабом
(решение Оператора 03.09): временная реализация правила требования 1/2
БЕЗ обработки `mockup.html` (общий top-level scan по образцу
`scan_extraneous_acceptance_files`, без исключения для T080) на
настоящем дереве `tasks/` этого репозитория красит `guard --all` именно
строкой `tasks/T080/mockup.html: посторонний файл в каталоге задачи` —
тест поймал бы этот пробел, если бы разработчик забыл про AC-3; тот же
стаб С добавленным исключением для `tasks/T080/mockup.html` зеленил этот
тест. Стаб убран, репозиторий не тронут.

Прогон — реальный `python3 scripts/guard.py --all` подпроцессом от корня
репозитория (не синтетическая фикстура): решение AC-3 адресовано к
КОНКРЕТНОМУ файлу конкретной исторической задачи на `main`, а не к
абстрактному сценарию, который можно было бы воспроизвести временным
деревом.
"""
import subprocess
import sys
import unittest
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[3]

MOCKUP_REL = "tasks/T080/mockup.html"


class Ac3MockupHtmlNotFlaggedAsExtraneousTest(unittest.TestCase):

    def test_ac3_real_repo_guard_all_does_not_flag_mockup_html_as_extraneous(self):
        """`tasks/T080/mockup.html` — либо явно исключён решением AC-3 из
        PLAN.md и остаётся на диске, либо удалён отдельным приложением к
        PLAN; в обоих случаях `guard --all`, прогнанный от корня реального
        репозитория, не печатает по нему строку «посторонний файл в
        каталоге задачи».

        Ловит мутацию: разработчик реализует белый список первого уровня
        `tasks/<id>/` (требования 1-2 SPEC) БЕЗ решения AC-3 — тогда
        `tasks/T080/mockup.html` (реально присутствующий на `main` файл
        расширения `.html`, не входящего в перечень AC-1) получит именно
        эту именованную ошибку, и `assertNotIn` ниже это поймает.
        """
        mockup_path = _REPO_ROOT / MOCKUP_REL
        if not mockup_path.exists():
            self.skipTest(
                f"{MOCKUP_REL} отсутствует на диске — решение AC-3 уже "
                f"выбрало удаление; критерий выполнен по построению "
                f"(guard не может назвать посторонним несуществующий файл)")

        result = subprocess.run(
            [sys.executable, "scripts/guard.py", "--all"],
            cwd=_REPO_ROOT, capture_output=True, text=True, timeout=60)

        flagged_lines = [
            line for line in result.stdout.splitlines()
            if MOCKUP_REL in line and "посторонний файл в каталоге задачи" in line]
        self.assertEqual(
            flagged_lines, [],
            f"guard --all назвал {MOCKUP_REL} посторонним файлом каталога "
            f"задачи — AC-3 требует явного исключения (с указанием T080) "
            f"или удаления файла отдельным приложением к PLAN.md:\n"
            f"{result.stdout}")


if __name__ == "__main__":
    unittest.main()
