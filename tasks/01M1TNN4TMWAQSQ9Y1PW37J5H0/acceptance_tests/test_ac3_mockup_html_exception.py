"""AC-3 (SPEC 01M1TNN4TMWAQSQ9Y1PW37J5H0), формулировка по ANSWER-1
(tasks/01M1TNN4TMWAQSQ9Y1PW37J5H0/ANSWER-1.md, вариант A): белый список
AC-1 действует только для `*.md` первого уровня `tasks/<id>/`; файлы
любого другого расширения — вложения, допустимые без ограничений имени.
`tasks/T080/mockup.html` — расширение `.html`, не `.md` — из этого
прямо следует, что он становится законным вложением автоматически,
никакого отдельного решения в PLAN.md (исключение по имени задачи либо
удаление) не требуется — ANSWER-1 буквально снимает эту часть AC-3:
«AC-3... снимается: файл становится законным вложением, отдельного
решения в PLAN не требуется».

Тест поэтому не проверяет НИКАКОЕ решение PLAN — только наблюдаемое
следствие ANSWER-1: `guard --all`, прогнанный на настоящем дереве
`tasks/` репозитория, не называет `tasks/T080/mockup.html` посторонним.
Файл при этом обязан физически остаться на месте (ANSWER-1 не требует и
не разрешает его удаление) — тест такого не проверяет отдельно, но
`skipTest` ниже — на случай, если Оператор всё же решит убрать файл
отдельным приложением к PLAN, не блокировать переход по формальному
отсутствию файла.

Красен до реализации: белого списка первого уровня `tasks/<id>/` в guard.py сегодня нет вовсе, но это НЕ помечает mockup.html — см. маркер «Зелёный с рождения» ниже, это не тест этого файла.

Зелёный с рождения: белого списка первого уровня `tasks/<id>/` в guard.py сегодня нет вовсе, поэтому `mockup.html` не проверяется этим правилом и не помечается — тест фиксирует инвариант на будущее (после ANSWER-1 mockup.html обязан остаться непомеченным ЧЕРЕЗ общее правило «расширение вне .md — вложение», без специального исключения по имени задачи), не тавтологию.

Подробности: белого правила первого уровня `tasks/<id>/` в guard.py
сегодня нет вовсе (SPEC 01M1TNN4TMWAQSQ9Y1PW37J5H0, требования 1-2) —
`mockup.html` не проверяется этим правилом уже сегодня, поэтому `guard
--all` не называет его посторонним и сейчас. Это не тавтология: тест
фиксирует ИНВАРИАНТ, который обязан пережить появление правила
требования 1/2 (эта же SPEC) — как только оно появится СОГЛАСНО
ANSWER-1 (белый список только для `.md`, прочие расширения — вложения
без ограничений имени), `mockup.html` обязан остаться непомеченным
ОБЩИМ правилом «не .md — вложение», а не специальным исключением по
имени задачи T080, которое требовал первоначальный текст AC-3 ДО
ANSWER-1. Провалидировано стабом (решение Оператора 03.09): временная
реализация правила требования 1/2 ПО ANSWER-1 (whitelist только для
`.md`, прочие расширения пропускаются молча) на настоящем дереве
`tasks/` этого репозитория не красит `guard --all` по `mockup.html` —
тест остаётся зелёным без какого-либо специального исключения для
T080 в реализации. Тот же стаб, БЕЗ различения `.md`/прочих
расширений (буквальный whitelist AC-1 ДО правки ANSWER-1), красил
`guard --all` именно строкой `tasks/T080/mockup.html: посторонний файл
в каталоге задачи» — тест поймал бы такую реализацию. Стаб убран,
репозиторий не тронут.

Прогон — реальный `python3 scripts/guard.py --all` подпроцессом от корня
репозитория (не синтетическая фикстура): решение ANSWER-1 адресовано к
КОНКРЕТНОМУ файлу конкретной исторической задачи на `main`, а не к
абстрактному сценарию, который можно было бы воспроизвести временным
деревом.
"""
import subprocess
import sys
import unittest
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[3]

MOCKUP_REL = "tasks/T080/mockup.html"


class Ac3MockupHtmlNotFlaggedAsExtraneousTest(unittest.TestCase):

    def test_ac3_real_repo_guard_all_does_not_flag_mockup_html_as_extraneous(self):
        """`tasks/T080/mockup.html` — расширение `.html`, не входящее в
        перечень `.md`-имён AC-1, поэтому по ANSWER-1 — законное вложение
        без ограничений имени; `guard --all`, прогнанный от корня
        реального репозитория, не печатает по нему строку «посторонний
        файл в каталоге задачи».

        Ловит мутацию: разработчик реализует белый список первого уровня
        `tasks/<id>/` (требования 1-2 SPEC) БУКВАЛЬНО, без различения
        `.md`/прочих расширений по ANSWER-1 (т.е. как единый список
        имён/расширений AC-1 без понятия «вложение») — тогда
        `tasks/T080/mockup.html` (реально присутствующий на `main` файл
        расширения `.html`) получит именно эту именованную ошибку, и
        `assertEqual([], ...)` ниже это поймает.
        """
        mockup_path = _REPO_ROOT / MOCKUP_REL
        if not mockup_path.exists():
            self.skipTest(
                f"{MOCKUP_REL} отсутствует на диске — Оператор решил "
                f"убрать файл отдельным приложением к PLAN несмотря на "
                f"то, что ANSWER-1 такого удаления не требует; критерий "
                f"выполнен по построению (guard не может назвать "
                f"посторонним несуществующий файл)")

        result = subprocess.run(
            [sys.executable, "scripts/guard.py", "--all"],
            cwd=_REPO_ROOT, capture_output=True, text=True, timeout=60)

        flagged_lines = [
            line for line in result.stdout.splitlines()
            if MOCKUP_REL in line and "посторонний файл в каталоге задачи" in line]
        self.assertEqual(
            flagged_lines, [],
            f"guard --all назвал {MOCKUP_REL} посторонним файлом каталога "
            f"задачи — по ANSWER-1 файл расширения .html является "
            f"законным вложением автоматически, без отдельного решения "
            f"PLAN:\n{result.stdout}")


if __name__ == "__main__":
    unittest.main()
