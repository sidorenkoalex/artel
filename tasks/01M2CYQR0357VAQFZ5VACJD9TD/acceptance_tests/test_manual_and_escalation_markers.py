# AC-3: escalate — буквальная реализация AC-1 (пакет `orchestrator/
# gates/` по имени, названному требованием 1 SPEC дословно) СТРУКТУРНО
# противоречит AC-3 («полный набор tests/ зелёный», «поведение не
# меняется»): в `orchestrator/` уже существует НЕСВЯЗАННЫЙ модуль
# `orchestrator/gates.py` (политика гейтов из `gates.yaml`, ADR-0007/
# T066 — `policy()`, `AUTO`, `MANUAL`), от которого зависят
# `orchestrator/fsm_autogate.py` (`gates.policy("acceptance") !=
# gates.AUTO`, вне зон этой задачи) и `tests/test_gates.py` (9 тестов,
# внутри `tests/`, но НЕ в списке требования 4 — их логика перенос не
# трогает).
#
# Python при разрешении `import orchestrator.gates` отдаёт приоритет
# ОДНОИМЁННОМУ ПАКЕТУ-ДИРЕКТОРИИ над МОДУЛЕМ-ФАЙЛОМ: как только рядом с
# `orchestrator/gates.py` появляется каталог `orchestrator/gates/` с
# `__init__.py`, имя `orchestrator.gates` начинает резолвиться в НОВЫЙ
# пакет, а старый флэт-модуль становится НЕДОСТИЖИМ обычным импортом —
# не предупреждение, а факт итератора путей CPython (`FileFinder`
# проверяет директории с `__init__.py` раньше одиночных `.py`-файлов
# того же имени).
#
# Проверено эмпирически теми же средствами, что требует test-authoring.md
# («провалидируй тесты временным стабом корректной реализации»): пакет
# `orchestrator/gates/` материализован ДОСЛОВНЫМ переносом кода
# требования 1 (все шесть файлов + `__init__.py`), в `orchestrator/
# fsm_advance.py` добавлены алиасы требования 2 — ровно то, что просит
# AC-1/AC-2. После этого:
#   from orchestrator import gates
#   gates.__file__            # .../orchestrator/gates/__init__.py (не gates.py)
#   hasattr(gates, "policy")  # False
#   python3 -m pytest tests/test_gates.py -q
#   # 9 failed — AttributeError: module 'orchestrator.gates' has no
#   # attribute 'policy' (во всех девяти методах GatesPolicyTest)
# Стаб отменён без остатка сразу после проверки (`git checkout --
# orchestrator/fsm_advance.py`, каталог `orchestrator/gates/` удалён) —
# репозиторий на момент сдачи планки не тронут.
#
# Починить это В РАМКАХ ЗОН ЗАДАЧИ нельзя: `orchestrator/gates.py` и
# `orchestrator/fsm_autogate.py` не входят в зоны SPEC (только
# `orchestrator/gates/__init__.py`, `_base.py`, `zones.py`, `capacity.py`,
# `review.py`, `acceptance.py`, `tests_writing.py`, `orchestrator/
# fsm_advance.py`, `docs/codebase-map.md`, `tests/`) — а единственный
# способ сохранить `tests/test_gates.py` зелёным (переименовать или
# слить старый `orchestrator/gates.py`) требует правки именно этих
# файлов вне зон. Ирония: гейт, который отказал бы такую правку —
# `_zones_gate` — это ОДНА ИЗ ФУНКЦИЙ, переносимых этой же задачей.
#
# ## Эскалация
#
# Вопросы (по блокирующести, у каждого — дефолт на случай молчания):
#
# 1. (блокирует старт реализации целиком) Как разрешить коллизию имён
#    `orchestrator/gates.py` (существующий, политика `gates.yaml`) vs
#    `orchestrator/gates/` (новый пакет этой задачи)?
#    а) расширить зоны задачи на `orchestrator/gates.py`,
#       `orchestrator/fsm_autogate.py`, `tests/test_gates.py`,
#       `tests/test_fsm_autogate.py` и переименовать/слить старый
#       модуль (см. вопрос 2);
#    б) оставить `orchestrator/gates.py` нетронутым и назвать новый
#       пакет иначе (например `orchestrator/state_gates/`) — тогда
#       требование 1 и AC-1 SPEC меняются текстом (новый путь пакета);
#    в) отменить перенос части «зон» файла (наименее вероятный вариант,
#       не решает проблему сам по себе — коллизия свойство ИМЕНИ
#       пакета, не конкретного файла-получателя).
#    Дефолт при молчании: не продолжать реализацию — любой выбор без
#    ответа рискует либо непроходимым AC-3 (вариант «как есть»), либо
#    неавторизованной правкой вне зон.
#
# 2. (актуален только при ответе (а) на вопрос 1) Куда девать
#    содержимое старого `orchestrator/gates.py` (`policy`, `AUTO`,
#    `MANUAL`)? Варианты: переименовать файл (например
#    `orchestrator/gate_policy.py`, обновив импорт в
#    `fsm_autogate.py`/`tests/test_gates.py`) либо перенести его
#    содержимое в `orchestrator/gates/__init__.py` вместе с реэкспортом
#    перенесённых требованием 1 имён. Дефолт при молчании — не решать
#    самостоятельно (оба варианта одинаково меняют импорт в файле вне
#    исходных зон, выбор — за Оператором).
#
# Контекст: обнаружено при обязательной стаб-валидации тестов AC-1/AC-2
# этой же планки (test_ac1_gates_package_created.py,
# test_ac2_fsm_advance_handlers_and_aliases.py) — оба теста, как
# описано, зеленеют под стабом; сама коллизия — свойство ИМЕНИ пакета,
# не ошибка в тексте этих тестов.
#
# Блокирует: AC-3 («полный набор tests/ зелёный», «поведение не
# меняется») не может быть ни подтверждён тестом, ни признан
# выполнимым при буквальном пути `orchestrator/gates/` из AC-1 —
# реализация по SPEC либо ломает `tests/test_gates.py` (пакет назван
# буквально), либо не выполняет AC-1 (пакет не создан/назван иначе).

