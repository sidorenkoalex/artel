"""AC-1, AC-2, AC-4 — содержание текста синтетического ответа канарейки:
ни одного идентификатора задачи, ни слова «вариант», адрес допущения по
существующему разделу шаблонов.

Источник — SPEC.md, «Критерии приёмки»:

AC-1. Текст синтетического ответа не содержит ни одной подстроки формата
идентификатора задачи пульта (26 символов алфавита Crockford base32 —
формат генератора `orchestrator/idgen.py::new_task_id`). Проверка —
регулярным выражением этого формата, не литералом номера: тест обязан
краснеть на любом номере задачи в тексте, не только на прежнем.

AC-2. Текст не содержит слова «вариант» ни в одном падеже.

AC-4. Текст называет раздел `## Риски` и оговорку для артефакта без
такого раздела; каждый заголовок вида `## <название>`, названный в
тексте, существует заголовком хотя бы в одном файле `templates/*.md`.

Красен до реализации: прежний текст `canary._pass_escalated_with_
synthetic_answer` несёт номер задачи, которая ввела механизм, и «вариант
A», а раздела `## Риски` не называет вовсе — падают все четыре метода
файла.

Оговорка AC-4 («шаблон твоего артефакта такого раздела не несёт»)
проверяется той частью, которая механически наблюдаема: раздел `##
Риски` в тексте назван, и НИ ОДИН названный в тексте раздел не выдуман —
именно это условие делает оговорку исполнимой для роли, чей шаблон
раздела не несёт. Формулировку самой оговорки планка не диктует: любое
её словесное исполнение законно, а сверка чужой формулировки с копией
литерала в планке (её пришлось бы угадать здесь и сейчас) закрепила бы
под локом не критерий, а вкус автора тестов.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

import _synthetic_answer  # noqa: E402
from orchestrator import config, idgen, store  # noqa: E402
from tests.sandbox import SchemaConnTmpRootTest  # noqa: E402


class SyntheticAnswerTextTest(SchemaConnTmpRootTest):
    """Текст, который канарейка отдаёт каналу ANSWER, — наблюдается
    подменой `answer.cmd_answer` (см. `_synthetic_answer.answer_text`)."""

    def setUp(self):
        super().setUp()
        store.insert_task(self.conn, _synthetic_answer.TASK,
                          "Канареечная задача прогона", "escalated",
                          f"task/{_synthetic_answer.TASK.lower()}-kanareyka",
                          config.DEFAULT_TARGET, 25.0, is_canary=True)
        self.text = _synthetic_answer.answer_text(self.conn,
                                                  _synthetic_answer.TASK)

    def test_ac1_text_carries_no_task_identifier_in_generator_format(self):
        """Текст ответа не несёт ни одной подстроки формата идентификатора
        задачи — проверка образцом формата генератора, а не номером
        задачи, которая ввела механизм.

        Регулярное выражение проверяется на себя двумя сторонами: оно
        обязано находить идентификаторы, которые генератор реально
        выдаёт, и не находить их там, где их нет — иначе «текст чист»
        означало бы «выражение ничего не ищет».

        Ловит мутацию: в текст вернули любой номер задачи — прежний номер
        SPEC механизма, номер задачи прогона из `task_id` или номер
        соседней задачи; текст ответа, который читает роль, снова
        называет идентификатор, и тест краснеет на любом из них.
        """
        for _ in range(30):
            generated = idgen.new_task_id()
            self.assertRegex(generated, _synthetic_answer.ID_IN_TEXT,
                             "образец формата не узнаёт идентификатор "
                             "собственного генератора пульта")
        self.assertIsNone(
            _synthetic_answer.ID_IN_TEXT.search(
                "текст без идентификатора задачи вовсе"),
            "образец формата находит идентификатор там, где его нет")

        found = _synthetic_answer.ID_IN_TEXT.findall(self.text)
        self.assertEqual([], found,
                         f"текст ответа несёт идентификатор задачи: {found}\n"
                         f"--- текст ---\n{self.text}")

    def test_ac2_text_does_not_offer_a_lettered_option(self):
        """Текст ответа не содержит слова «вариант» ни в одном падеже:
        роль могла не предлагать вариантов вовсе, и ссылка на «вариант A»
        читается ею как ответ по чужим вопросам.

        Сверяется основа слова без окончания — она общая у всех падежей и
        чисел («варианта», «варианте», «вариантов», «варианты»), регистр
        не учитывается.

        Ловит мутацию: в текст вернули ссылку на вариант ответа («вариант
        A», «первый вариант», «вариантом A») — текст снова адресует
        развилку, которой в вопросах роли может не быть, и тест краснеет.
        """
        self.assertNotIn("вариант", self.text.lower(),
                         f"текст ответа ссылается на вариант:\n{self.text}")

    def test_ac4_text_addresses_the_assumption_to_the_risks_section(self):
        """Текст называет роли адрес допущения — раздел `## Риски`
        (единственный раздел под допущения/риски среди шаблонов
        артефактов).

        Ловит мутацию: адрес допущения из текста убрали или заменили
        безадресным «запиши в артефакт» — роль получает ответ без места,
        куда писать выбранное толкование, и тест краснеет.
        """
        self.assertIn("## Риски", self.text,
                      f"текст не называет раздел `## Риски`:\n{self.text}")

    def test_ac4_every_section_named_in_text_exists_in_templates(self):
        """Каждый раздел `## <название>`, названный в тексте ответа,
        существует заголовком хотя бы в одном шаблоне `templates/*.md`:
        `templates/` — защищённый путь только для чтения, и раздела,
        которого нет ни в одном шаблоне, текст требовать не может.

        Ловит мутацию: текст адресует допущение в раздел, которого ни
        один шаблон не несёт («## Допущения», «## Открытые вопросы») —
        роль получает недостижимый адрес; названный раздел не найдётся
        среди заголовков шаблонов, и тест краснеет.
        """
        headings = _synthetic_answer.template_headings()
        self.assertIn("Риски", headings,
                      "ни один шаблон не несёт раздела `## Риски` — "
                      "предпосылка критерия про шаблоны изменилась")
        named = _synthetic_answer.headings_named_in(self.text)
        self.assertTrue(named, f"текст не называет ни одного раздела `## …`:"
                               f"\n{self.text}")
        unknown = [name for name in named
                   if not _synthetic_answer.heading_exists(name, headings)]
        self.assertEqual([], unknown,
                         f"текст называет разделы, которых нет ни в одном "
                         f"шаблоне templates/*.md: {unknown}")


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
