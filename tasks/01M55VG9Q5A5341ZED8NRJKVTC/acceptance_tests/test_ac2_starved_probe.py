"""Исход целевого теста не зависит от соотношения реального времени работы
пробника и предела N.

Группа: разовый
Красен до реализации: целевой тест обрывает прогон по реальным часам — пока группа процессов пробника заморожена дольше N, настоящий proc.wait обрывает прогон до события «start», и утверждение о старте пробника краснеет.

Нагрузка моделируется детерминированно (`_mutant.py`): в размеченной копии
первый вызов `proc.wait(timeout=limit[0])` фонового процесса (прогон ветки,
`orchestrator/suite_run.py:581`) замораживает группу процессов прогона
SIGSTOP на «N + 3 с» реального времени и затем отпускает SIGCONT — машина,
на которой пробник не получил процессора дольше предела.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _mutant  # noqa: E402


class StarvedProbeTest(unittest.TestCase):

    def test_ac2_outcome_survives_probe_starved_longer_than_limit(self):
        """Пробник без процессора дольше N — целевой тест всё равно зелёный.

        Сценарий: группа процессов прогона ветки заморожена на N + 3 с
        реального времени сразу после запуска (пробник ещё не записал
        «start»); целевой тест зелёный, заморозка действительно была.

        Ловит мутацию: обрыв по-прежнему по реальным часам (настоящие N
        секунд в proc.wait) — прогон оборван, пока пробник заморожен, события
        «start» нет, целевой тест красен, метод красен.
        """
        run = _mutant.instrumented_run(freeze=True)
        self.assertTrue(any(c.frozen for c in run.calls), run.context(
            "заморозка прогона ветки не состоялась"))
        self.assertTrue(run.green, run.context(
            "целевой тест красен при пробнике, замороженном дольше N"))


if __name__ == "__main__":
    unittest.main()
