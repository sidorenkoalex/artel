"""AC-9 — 01M3HST1381E1FZCYAN2TSB1F3: раздел «Провайдер codex» в
`docs/stack.md` называет обе половины.

Источник — SPEC.md, «Критерии приёмки»:

AC-9. `docs/stack.md`, раздел «Провайдер codex», называет: что прогон
канарейки переносит указатель связки ключей копией в дом роли клона на
наборах с ролью на Codex, и что установка указателя в главном доме роли
вместе с самим `codex login` остаётся однократным шагом Оператора.

Текст ищется ИМЕННО в разделе «Провайдер codex» (`_util.DocsSectionTest.
section_text`), а не по всему файлу: тот же абзац, дописанный в соседний
раздел, критерия не закрывает — Оператор, читающий про Codex, его там не
найдёт.

И не «слово встречается где-нибудь в разделе»: раздел на 250 строк уже
несёт по отдельности и «канарейк», и «указател», и «копи», и «набор» —
поиск по всему разделу зеленел бы, не дождавшись ни строчки правки.
Поэтому каждая половина критерия ищется в ОКНЕ строк вокруг своего якоря
(`_window_has`): критерий требует утверждения, то есть слов рядом друг с
другом, а не рассыпанных по разделу.

Критерий называет смысл, не формулировку, поэтому внутри окна сверяются
корни слов в нижнем регистре, а не эталонный абзац: эталон красил бы планку
на любой правке стиля.

Вторую половину критерий требует СОХРАНИТЬ, а не дописать: сегодняшний
раздел уже говорит про два однократных шага Оператора — критерий запрещает
вычеркнуть это вместе с правкой про канарейку.

Красен до реализации: рядом с упоминанием канарейки раздел сегодня говорит
про живой запуск Codex для прогона, а не про перенос указателя в дом роли
клона — ни «клон», ни «указател» в окне около «канарейк» нет.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import _util  # noqa: E402

#: Полуокно строк, внутри которого слова считаются сказанными рядом. 15 —
#: с запасом на абзац с командой в отступе (сегодняшний абзац про два
#: однократных шага Оператора занимает 14 строк вместе с обеими командами).
WINDOW = 15

#: Якорь первой половины и корни слов, которые критерий требует рядом с ним:
#: кто переносит (канарейка), что (указатель), каким способом (копия), куда
#: (дом роли клона) и на каких прогонах (набор).
TRANSFER_ANCHOR = "канарейк"
TRANSFER_ROOTS = ("указател", "копи", "клон", "набор")

#: Якорь второй половины и корни слов рядом с ним: однократность, сам
#: указатель, Оператор и команда входа.
OPERATOR_ANCHOR = "однократн"
OPERATOR_ROOTS = ("указател", "оператор", "login")


class DocsStackCodexSectionTest(_util.DocsSectionTest):

    def _windows(self, anchor: str) -> list:
        """Окна строк раздела вокруг каждого вхождения якоря `anchor`."""
        lines = self.section_text().splitlines()
        return ["\n".join(lines[max(0, index - WINDOW):index + WINDOW + 1])
                for index, line in enumerate(lines) if anchor in line]

    def _missing_near(self, anchor: str, roots) -> list:
        """Корни, которых не нашлось ни в одном окне вокруг якоря — либо
        сам якорь, если его в разделе нет вовсе."""
        windows = self._windows(anchor)
        if not windows:
            return [f"якоря «{anchor}» в разделе нет"]
        return min((([root for root in roots if root not in window])
                    for window in windows), key=len)

    def test_ac9_section_says_the_canary_copies_the_pointer_into_the_clone(self):
        """Рядом с упоминанием канарейки раздел называет перенос указателя
        связки ключей копией в дом роли клона и наборы, на которых он идёт.

        Ловит мутацию: механика реализована, а документация о ней молчит —
        Оператор, увидев отказ прогона «указателя нет», не нашёл бы в
        документации пульта ни того, что канарейка указатель переносит, ни
        того, каким способом и на каких наборах, и искал бы ответ в SPEC
        закрытой задачи.
        """
        missing = self._missing_near(TRANSFER_ANCHOR, TRANSFER_ROOTS)

        self.assertEqual(
            [], missing,
            f"в разделе «{self.SECTION_TITLE}» рядом с «{TRANSFER_ANCHOR}» "
            f"не сказано: {missing}")

    def test_ac9_section_keeps_the_one_time_operator_step(self):
        """Раздел по-прежнему называет установку указателя в ГЛАВНОМ доме
        роли вместе с входом однократным шагом Оператора.

        Ловит мутацию: абзац про два однократных шага Оператора вычеркнут
        как «теперь это делает канарейка» — пульт перестал бы объяснять, где
        указатель берётся изначально, и после потери `.artel/home` Оператор
        не знал бы, что вход нужно ставить заново руками.
        """
        missing = self._missing_near(OPERATOR_ANCHOR, OPERATOR_ROOTS)

        self.assertEqual(
            [], missing,
            f"в разделе «{self.SECTION_TITLE}» рядом с «{OPERATOR_ANCHOR}» "
            f"не сказано: {missing}")


if __name__ == "__main__":
    unittest.main()
