"""AC-4 — для тестового МЕТОДА разрешена форма «Зелёный с рождения: …»
вместо заявки мутации, и именно тогда, когда мутации с наблюдаемым
расхождением нет.

Источник — SPEC.md, «Критерии приёмки»:

AC-4. Там же для тестового метода разрешена форма
«Зелёный с рождения: <что держит>» вместо строки «Ловит мутацию: …» —
именно для случая, когда мутации с наблюдаемым расхождением нет.

Проверяется абзац скила `skills/test-authoring.md` после применения
приложений PLAN к базе сравнения (см. `_appendix`): абзац, который
одновременно называет эту форму, говорит о методе и называет условие, при
котором форма разрешена. Маркер красноты ниже относится к самой планке, не
к этой форме в скиле.

Красен до реализации: приложения на `skills/test-authoring.md` ещё нет —
в базе сравнения «Зелёный с рождения» назван только маркером ФАЙЛА
планки (раздел о красноте) и ни один абзац не разрешает эту форму
тестовому методу вместо заявки мутации.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _appendix  # noqa: E402

GREEN_FORM = "Зелёный с рождения"


class GreenFromBirthForMethodTest(unittest.TestCase):

    def setUp(self):
        self.state = _appendix.state()
        self.text = _appendix.applied_text(_appendix.TEST_AUTHORING)
        # Абзацы, в которых форма предложена ИМЕННО тестовому методу и
        # именно вместо заявки мутации: сам маркер файла планки в разделе
        # о красноте под критерий не подходит.
        self.candidates = [
            p for p in _appendix.paragraphs_with(self.text, GREEN_FORM)
            if _appendix.has(p, "метод")
            and (_appendix.has(p, "вместо")
                 or _appendix.has(p, _appendix.MUTATION_CLAIM_MARK))]

    def test_ac4_green_form_allowed_for_test_method(self):
        """В скиле есть абзац, разрешающий тестовому методу форму «Зелёный
        с рождения: …» вместо строки заявки мутации.

        Ловит мутацию: правка разрешила форму, но говорит о ней по-прежнему
        только применительно к файлу планки (слова о тестовом методе и о
        замене заявки мутации в абзаце не появилось) — ровно тот пробел,
        который назван в «Контексте» SPEC: скил знает маркер только для
        файла. Список подходящих абзацев останется пустым.
        """
        self.assertTrue(
            self.text,
            f"текст `{_appendix.TEST_AUTHORING}` после применения приложений "
            f"пуст ({self.state.diagnosis()})")
        self.assertTrue(
            self.candidates,
            f"в `{_appendix.TEST_AUTHORING}` нет абзаца, который разрешал бы "
            f"тестовому МЕТОДУ форму «{GREEN_FORM}: …» вместо заявки мутации "
            f"(ищется абзац с «{GREEN_FORM}», словом «метод» и «вместо»/"
            f"«{_appendix.MUTATION_CLAIM_MARK}») ({self.state.diagnosis()})")

    def test_ac4_green_form_only_without_observable_mutation(self):
        """Тот же абзац называет условие, при котором форма разрешена:
        мутации с наблюдаемым расхождением нет.

        Ловит мутацию: правка разрешила форму методу без условия — как
        свободную альтернативу заявке мутации (тогда её выберет любой тест,
        которому лень искать мутацию) — в абзаце не будет ни наблюдаемого
        расхождения, ни отрицания, и проверка покраснеет.
        """
        self.assertTrue(
            self.candidates,
            f"абзаца о форме «{GREEN_FORM}» для тестового метода нет вовсе — "
            f"условие проверять не на чем ({self.state.diagnosis()})")
        conditioned = [p for p in self.candidates
                       if _appendix.has(p, "наблюдаем")
                       and _appendix.has(p, "расхожден")
                       and _appendix.has_negation(p)]
        self.assertTrue(
            conditioned,
            f"абзац о форме «{GREEN_FORM}» для тестового метода не называет "
            f"условия «мутации с наблюдаемым расхождением нет» (ищутся "
            f"«наблюдаем», «расхожден» и отрицание в том же абзаце) "
            f"({self.state.diagnosis()})")


if __name__ == "__main__":
    unittest.main()
