"""AC-2 — заявка мутации требует назвать наблюдаемое расхождение, а
поведенчески нейтральная подмена в заявку не пишется.

Источник — SPEC.md, «Критерии приёмки»:

AC-2. После применения приложения раздел `skills/test-authoring.md` о
заявке мутации требует назвать наблюдаемое расхождение — что изменится в
выводе, состоянии или вызовах — и прямо говорит, что поведенчески
нейтральная подмена в заявку не пишется.

Проверяется текст скила ПОСЛЕ применения приложений PLAN к базе сравнения
(см. `_appendix`), раздел — тот, что называет маркер `Ловит мутацию`
(критерий адресует место словами «раздел о заявке мутации», не
заголовком).

Красен до реализации: приложения на `skills/test-authoring.md` ещё нет,
текст раздела равен базе сравнения — в нём нет ни требования назвать
наблюдаемое расхождение, ни тройки «вывод/состояние/вызовы», ни слова о
поведенчески нейтральной подмене.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _appendix  # noqa: E402

# Три наблюдаемые поверхности, названные критерием дословно.
OBSERVABLE_SURFACES = ("вывод", "состояни", "вызов")


class MutationClaimNamesObservableDifferenceTest(unittest.TestCase):

    def setUp(self):
        self.state = _appendix.state()
        self.section = _appendix.mutation_claim_text(
            _appendix.applied_text(_appendix.TEST_AUTHORING))

    def test_ac2_claim_requires_observable_difference(self):
        """Раздел о заявке мутации требует назвать НАБЛЮДАЕМОЕ расхождение
        и перечисляет, где оно наблюдается: в выводе, в состоянии или в
        вызовах.

        Ловит мутацию: правка говорит про наблюдаемость вообще, но не
        называет, где расхождение наблюдают (одна из трёх поверхностей
        выпала из перечисления — например, «вызовы», ради которых AC-3
        отдельно вводит приём подмены) — проверка покраснеет, назвав
        недостающее слово.
        """
        self.assertTrue(
            self.section,
            f"в `{_appendix.TEST_AUTHORING}` после применения приложений нет "
            f"ни одного раздела о заявке мутации "
            f"({self.state.diagnosis()})")
        absent = _appendix.missing(self.section, ("наблюдаем", "расхожден"))
        self.assertEqual(
            [], absent,
            f"раздел о заявке мутации не требует назвать наблюдаемое "
            f"расхождение (нет слов: {absent}) ({self.state.diagnosis()})")
        absent = _appendix.missing(self.section, OBSERVABLE_SURFACES)
        self.assertEqual(
            [], absent,
            f"раздел о заявке мутации не называет, где расхождение "
            f"наблюдается — нет упоминаний: {absent} "
            f"({self.state.diagnosis()})")

    def test_ac2_neutral_substitution_is_not_claimed(self):
        """Тот же раздел прямо говорит, что поведенчески нейтральная
        подмена в заявку не пишется: есть фраза, в которой рядом стоят
        нейтральность подмены, отрицание и сама заявка/мутация.

        Ловит мутацию: правка ограничилась требованием наблюдаемости и
        промолчала о нейтральной подмене (ровно тот случай, который стоил
        трём задачам круга ревью) — фразы с «нейтральн» в разделе не
        появится, и проверка покраснеет.
        """
        candidates = [s for s in _appendix.sentences_with(self.section,
                                                          "нейтральн")
                      if _appendix.has_negation(s)
                      and (_appendix.has(s, "заявк") or _appendix.has(s, "мутаци"))]
        self.assertTrue(
            candidates,
            f"в разделе о заявке мутации нет фразы о том, что поведенчески "
            f"нейтральная подмена в заявку НЕ пишется (ищется предложение с "
            f"«нейтральн», отрицанием и словом «заявка»/«мутация») "
            f"({self.state.diagnosis()})")


if __name__ == "__main__":
    unittest.main()
