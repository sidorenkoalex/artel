"""AC-8 (tasks/01M1GV6H5DDDCWW4G3GW1D3A1X/SPEC.md): строка внутри
содержимого компонента, имитирующая формат граничного маркера (тот же
текстовый вид, но с чужим или отсутствующим идентификатором текущего
запуска), не распознаётся протоколом чтения как настоящая закрывающая
граница текущего запуска.

## Как тест ставит вопрос без знания формата маркера

Никакой машинный код не «читает» границы за роль (чтение — работа
LLM-агента по текстовой инструкции, не парсер оркестратора) — поэтому
единственное, что здесь проверяемо КОДОМ, это то, что имитация
находится внутри протестированного механизма: реальная закрывающая
граница ТЕКУЩЕГО запуска не совпадает с текстом, полученным из ЧУЖОГО
(другого) запуска, и продолжает стоять на своём месте — сразу после
подлинного конца содержимого — независимо от того, что где-то раньше в
том же содержимом уже встретилась строка того же текстового вида с
чужим id.

Строка-имитация конструируется буквально по определению самой AC-8: это
— настоящая закрывающая граница ОДНОГО запуска (запуск A), несущая ЧУЖОЙ
для другого запуска (запуск B) id; она встраивается в содержимое SPEC.md
запуска B. Тест не придумывает свой формат маркера — использует ровно
тот, что уже произвела реализация в соседнем прогоне.

Красен до реализации: без маркеров нечего извлекать как «строку того же
текстового вида» — `marker_id_for`/`marker_span` бросают
`AssertionError` уже на запуске A.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _sandbox import BriefSandbox, MAP_FRESH, marker_id_for, marker_span  # noqa: E402


class Ac8SpoofedMarkerIsInertTest(BriefSandbox):

    def test_ac8_a_foreign_run_closing_marker_embedded_in_content_does_not_terminate_the_block_early(self):
        """Ловит мутацию: протокол/код по ошибке считает ЛЮБУЮ строку
        нужного текстового вида настоящей закрывающей границей (например
        поиском первого совпадения формата без сверки id) — тогда
        встроенная чужая граница обрывала бы блок раньше настоящего
        конца содержимого, и хвост (`genuine_tail`) остался бы СНАРУЖИ
        настоящей пары маркеров запуска B."""
        # Запуск A: получаем подлинный текст закрывающей границы,
        # которую произвела реализация для КАКОГО-ТО запуска.
        text_a = self.build_developer_brief()
        map_id_a = marker_id_for(text_a, MAP_FRESH.strip())
        _open_a, close_a = marker_span(text_a, MAP_FRESH.strip(), map_id_a)
        # Строка вида «...та же граница...», как она выглядит целиком —
        # окно сразу после конца содержимого карты, где стоит закрывающий
        # маркер запуска A.
        foreign_marker_line = text_a[close_a - 2:close_a + len(map_id_a) + 2]
        self.assertIn(map_id_a, foreign_marker_line)

        # Запуск B: другое содержимое SPEC.md, несущее внутри себя ровно
        # эту подлинную закрывающую границу ЧУЖОГО (A) запуска — то есть
        # строку «того же текстового вида, но с чужим... идентификатором
        # текущего запуска» (AC-8, дословно).
        genuine_tail = "SPEC-TAIL-AFTER-SPOOF-AC8"
        self.write_spec(
            "# SPEC\n\nМаркер-текста-SPEC.\n\n" + foreign_marker_line
            + "\n\n" + genuine_tail + "\n")

        text_b = self.build_developer_brief()

        # id запуска B получаем от ДРУГОГО, не тронутого компонента того
        # же запуска (карта) — тот же приём, что и в AC-1/AC-3: все
        # компоненты одного запуска делят один и тот же id.
        map_id_b = marker_id_for(text_b, MAP_FRESH.strip())
        self.assertNotEqual(
            map_id_a, map_id_b,
            "запуски A и B обязаны получить разные id (AC-3) — иначе тест "
            "ничего не показывает про ЧУЖОЙ id")

        # Имитация чужой границы обязана остаться в тексте буквально —
        # как инертные данные компонента, не как команда протоколу.
        self.assertIn(
            foreign_marker_line, text_b,
            "встроенная чужая граница обязана остаться в теле компонента "
            "как обычный текст, не вырезаться")

        # Подлинный «хвост» содержимого SPEC.md запуска B, идущий ПОСЛЕ
        # имитации, обязан остаться ВНУТРИ настоящей пары маркеров
        # запуска B — то есть найтись между открывающим и закрывающим
        # маркерами id=map_id_b/spec_id_b этого же запуска.
        spec_id_b = marker_id_for(text_b, genuine_tail)
        self.assertEqual(
            spec_id_b, map_id_b,
            "хвост содержимого после имитации обязан остаться частью "
            "того же, настоящего блока запуска B, закрытого настоящим id")

        open_b, close_b = marker_span(text_b, genuine_tail, spec_id_b)
        idx_foreign = text_b.index(foreign_marker_line)
        self.assertGreater(
            idx_foreign, open_b,
            "имитация чужой границы обязана оказаться ВНУТРИ тела "
            "компонента запуска B — после настоящего открывающего "
            "маркера, как обычные данные, а не заменять его")
        self.assertLess(
            idx_foreign, close_b,
            "настоящая закрывающая граница запуска B обязана стоять "
            "ПОСЛЕ имитации чужой границы, встроенной в контент — "
            "имитация с чужим id не обрывает блок раньше срока")


if __name__ == "__main__":
    unittest.main()
