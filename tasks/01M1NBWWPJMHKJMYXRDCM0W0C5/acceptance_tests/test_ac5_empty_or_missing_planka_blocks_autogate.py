"""AC-5 (SPEC): задача, у которой каталог `acceptance_tests/` в
источнике артефактов пуст или отсутствует, не проходит автогейт с
причиной «автогейт: каталог приёмочных тестов пуст или отсутствует»
(то же поведение, что и раньше при пустом/отсутствующем каталоге —
теперь проверяется по ветке, а не по диску).

Зелёный с рождения: оба теста файла — сегодняшний код смотрит на диск
(`acc_tdir`), который в обоих сценариях этого файла пуст/не создан
независимо от того, что закоммичено в артефактную ветку — совпадает с
ожидаемой причиной случайно, тем же путём диска, что и после A7 вообще
(SPEC «Контекст»). Различие с AC-2..AC-4 (`test_ac2`/`test_ac3`/
`test_ac4`, там до правки код отвечает ЭТОЙ ЖЕ причиной, но
НЕПРАВИЛЬНО — планка ветки на самом деле не пуста) в том, что здесь
планка ветки ДЕЙСТВИТЕЛЬНО пуста/отсутствует в обоих случаях — и
диск, и (будущее) чтение ветки сходятся на одном ответе.

`test_ac5_empty_...` (каталог в ветке есть, но без `.py`-файлов)
не тавтологичен, несмотря на совпадение с сегодняшним поведением:
провалидирован временным стабом (обязательная самопроверка
test-authoring) — стаб, который считает «каталог с 0 `.py`-файлов»
уже отвечает на условие «а» (не отфильтровывает нужное расширение
файла в списке `ls_tree_files`), проваливает именно этот тест
(`state()` уходит в `merge_gate` вместо `acceptance`), тогда как
корректный стаб (фильтрует `.py`, тот же приём, что
`guard.scan_acceptance_tests`) зеленит оба теста файла. Тест ловит эту
мутацию РЕАЛИЗАЦИИ ветки, даже будучи сегодня зелёным по случайной
причине диска.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _sandbox import AutogateBranchSandbox  # noqa: E402
from orchestrator import artifact_branch  # noqa: E402

REASON = "автогейт: каталог приёмочных тестов пуст или отсутствует"


class EmptyOrMissingPlankaBlocksAutogateTest(AutogateBranchSandbox):

    def test_ac5_missing_acceptance_tests_directory_on_branch_blocks_autogate(self):
        """Ветка `artifact/<id>` существует (задача заведена — на ней
        закоммичен, например, SPEC.md), но каталога
        `acceptance_tests/` в её дереве вовсе нет. Автогейт не проходит,
        причина — «автогейт: каталог приёмочных тестов пуст или
        отсутствует».

        Ловит мутацию: если реализация трактует отсутствие каталога на
        ВЕТКЕ как «нечего проверять — пропускаем условие» (аналогично
        `acceptance.run()` для прогона, где отсутствие каталога легитимно),
        переход пройдёт автогейтом вместо отказа с этой причиной —
        `assertEqual(self.state(), "acceptance")` упадёт.
        """
        artifact_branch.commit_files(
            self.TASK, {f"tasks/{self.TASK}/SPEC.md": "# SPEC\n"},
            "тест: ветка без планки")

        out = self.autogate()

        self.assertEqual(self.state(), "acceptance")
        self.assertIn(REASON, out)

    def test_ac5_empty_acceptance_tests_directory_on_branch_blocks_autogate(self):
        """Каталог `acceptance_tests/` в ветке существует, но не несёт
        ни одного `*.py`-файла (например, только `README.md`) — тот же
        отказ, что и для полностью отсутствующего каталога (тем же
        приёмом, что и текущий код диска: `not tests_dir.is_dir() or not
        any(tests_dir.glob('*.py'))`).

        Ловит мутацию: наивная реализация, проверяющая только «каталог
        встречается в дереве» (`ls_tree_files` вернул непустой список
        путей вообще), но не отфильтровывающая нулевое число
        `.py`-файлов от прочего содержимого, пропустит этот случай
        дальше как «планка есть, 0 manual, 0 skip» — `assertIn(REASON,
        out)` не найдёт причину в выводе.
        """
        rel = f"tasks/{self.TASK}/acceptance_tests/README.md"
        artifact_branch.commit_files(
            self.TASK, {rel: "не тест, просто заметка\n"},
            "тест: планка без .py файлов")

        out = self.autogate()

        self.assertEqual(self.state(), "acceptance")
        self.assertIn(REASON, out)


if __name__ == "__main__":
    unittest.main()
