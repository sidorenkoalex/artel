"""Приёмочные тесты 01M1KS8K9RXWHX2PW3ZKB0P903 — AC-7 (guard принимает
SPEC со сработавшим сигналом, если секция «Оценка объёма и деление»
заполнена — нарезкой либо обоснованием монолита).

Триггер — та же фраза «ориентировочно», что и в test_ac5 (широта
распознавания фраз — предмет test_ac2). Проверяются оба допустимых вида
заполнения секции, которые называет AC-4: нарезка на подзадачи и
обоснование монолита.

Зелёный с рождения: сегодняшний guard.py не знает о секции «Оценка объёма
и деление» и потому принимает обе фикстуры уже сейчас — то же самое
верно и ПОСЛЕ реализации требования 3, раз секция заполнена. Тест —
защита от регрессии («заполнена, но недостаточно строго распознана как
заполненная» — например, реализация ищет только слово «монолит» и
отклоняет корректную нарезку), не проверка новой логики отказа.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from _sandbox import check  # noqa: E402

TRIGGER_SENTENCE = "Список затронутых файлов оценён ориентировочно."

DIVISION_TEXT = (
    "Деление на 2 части: часть 1 — модуль А (без зависимостей, мержится "
    "первой), часть 2 — модуль Б (зависит от части 1). Каждая часть "
    "самостоятельно мержима с зелёной планкой.")

MONOLITH_TEXT = (
    "монолит принят Оператором 04.09.2026: атомарная смена механики, "
    "промежуточное состояние неработоспособно.")


class SignalWithFilledSectionAcceptsTest(unittest.TestCase):
    """Оба допустимых вида заполнения секции (нарезка, обоснование
    монолита) принимаются guard'ом при сработавшем сигнале.

    Ловит мутацию: реализация распознаёт заполненной секцию только ОДНОГО
    из двух видов (например, требует буквальное слово «монолит» и
    отклоняет корректно оформленную нарезку без этого слова) —
    соответствующий subTest покраснеет.
    """

    def test_ac7_division_or_monolith_justification_both_pass(self):
        cases = {"нарезка": DIVISION_TEXT, "монолит": MONOLITH_TEXT}
        for label, volume_section in cases.items():
            with self.subTest(kind=label):
                errors = check(extra_requirement_sentence=TRIGGER_SENTENCE,
                               volume_section=volume_section)

                self.assertEqual(
                    errors, [],
                    f"guard отклонил SPEC со сработавшим сигналом и "
                    f"заполненной секцией «Оценка объёма и деление» "
                    f"(вид: {label}): {errors}")


if __name__ == "__main__":
    unittest.main()
