"""Приёмочный тест T080 — критерий без прямого теста (AC-8).

AC-8 («данные, показанные в макете, — статические примеры, списанные с
реального status/ретро текущего пульта, а не синтетические заглушки-
плейсхолдеры») размечен `manual`: критерий требует не наличия каких-то
данных в разметке (это уже проверяют AC-3/AC-4/AC-5/AC-6 — борд, карточка,
алерты, очередь гейтов не пустые), а ФАКТИЧЕСКОГО соответствия этих
данных реальной истории пульта — конкретным задачам, суммам расхода,
числу итераций ревью, реальным алертам/эскалациям из `docs/retro/*.md`
и вывода `artel status`/`artel log` (SPEC, раздел «Материалы»).

Автоматическая проверка такого соответствия недостижима: сама суть
критерия — «не выдумано» — принципиально не сводится к текстовому
паттерну, независимо от того, что покажет разметка. Правдоподобно
выглядящие, но фиктивные идентификаторы задач/суммы (например
придуманный «T999» с правдоподобной суммой) прошли бы любую regex-
проверку на формат, не будучи при этом настоящими данными пульта;
отличить их от подлинных можно только сверкой с конкретными файлами
docs/retro/*.md и историей `artel status`/`artel log`, которую держит
Оператор. Это же основание, что у прецедентов tasks/T037 AC-5/AC-6,
tasks/T046 AC-1/AC-3: критерий сам называет способ проверки, для
которого в этом репозитории нет тестового контура — ручная сверка на
приёмке.

Зелёный с рождения: файл не содержит ни одного unittest-метода — AC-8
размечен `manual` (см. маркер ниже), поэтому `unittest discover` просто
не находит здесь тестов для запуска и файл не может покраснеть; сверку
данных макета с docs/retro/*.md и artel status/log выполняет Оператор
руками на приёмке, а не код этого файла.
"""

