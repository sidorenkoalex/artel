# --check проходит на чистом дереве (протокол защищённого пути,
# conventions-core).» Тот же класс критерия, что уже применён
# tasks/01M1THKTJ7YT1K410G1KS17MK6/acceptance_tests/
# test_ac_manual_and_skip_markers.py (AC-11 там, диф-приложение на
# templates/+skills/) и tasks/01M1RDCCKBQMJ5G2K9ANJP059H/acceptance_tests/
# test_scope_markers.py (диф на .github/workflows/ci.yml): `skills/` —
# защищённый путь (skills/conventions-core.md, «правка ... skills/ ...
# эти пути меняет только Оператор отдельным MR»), правится ТОЛЬКО
# диф-приложением к PLAN.md, не прямой правкой в кодовой ветке задачи. К
# моменту прогона этой планки (до появления кода задачи) ни `skills/
# spec-authoring.md`, ни скил разработчика в ветке задачи не меняются —
# автотест против рабочей копии дал бы ложный результат независимо от
# качества диффа (файлы и не должны были измениться в этой ветке).
# `git apply --check` на чистом дереве — самопроверка разработчика перед
# сдачей (skills/conventions-core.md); сам факт приложения диффа и
# корректность калибровочных чисел в нём проверяет Оператор на гейте
# PLAN чтением приложенного текста.

