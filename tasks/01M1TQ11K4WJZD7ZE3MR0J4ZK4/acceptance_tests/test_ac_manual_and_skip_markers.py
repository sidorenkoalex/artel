# AC-3: manual — «docs/adr/0014-budget-default-and-role-cap.md ссылается
# на имя константы из AC-1, не дублирует числа калибровки отдельным
# текстом.» Имя константы/функции — интерфейс, который ПРИДУМАН этой же
# планкой (`_sandbox.py`, `orchestrator.budget.recommended_budget_usd`),
# а не назван SPEC буквально: у test_author нет гарантии, что
# разработчик не выберет для консультации Оператора на PLAN другое имя
# при обоснованном расхождении. Но даже при точном совпадении имени
# «ссылается на имя, не дублирует числа отдельным текстом» — это
# редакционное суждение о тексте ADR (адекватный ли это пересказ или всё
# ещё дублирование чисел прозой рядом), не механическое свойство: regex
# на отсутствие «$35»/«$45»/«$70» рядом с упоминанием константы ложно
# отклонил бы легитимный текст, оставляющий одно число примером
# («например $35»), и ложно принял бы текст, который называет константу,
# но по-прежнему подробно пересказывает калибровку своими словами.
# Читает и оценивает Оператор на гейте PLAN/приёмки, как и любую другую
# правку docs/adr/ вне зоны задачи.

# AC-4: manual — «PLAN.md несёт приложением unified-диф на skills/spec-
