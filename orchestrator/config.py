# 1) для команд `approve`: готовая к копированию строка вместо голого
# `<id>`, которую Оператору иначе приходится достраивать вручную
# (инцидент 02.09, мерж T101). Пусто — фиксации ещё нет, подсказка
# остаётся байт-в-байт прежней.
# `_BOTH_COMMANDS` (SPEC 01M28NX0M2WTVC38XVN75N01XD, требование 4/5,
# AC-4/AC-5) — литеральная фраза, называющая обе команды на ручном
# гейте/ожидании зоны: убить цикл (`kill`) — не то же, что штатно
# остановить его (`stop`), инцидент 11.09 (zones-extend, $14.42 потеряны
# из-за `kill` вместо `stop`). Общая строка, не дублируется по месту —
# `.format(id=...)`, как и остальные хинты этого словаря.
_BOTH_COMMANDS = ("stop {id} — остановить цикл; "
                  "kill {id} — ликвидировать задачу")

AUTO_STOP = {
    "spec_writing": ("SPEC ещё пишется",
                     "доведи SPEC.md до status: ready, затем artel.py advance {id}"),
    "spec_gate": ("гейт SPEC — решение Оператора",
                  "прочитай SPEC и: artel.py approve {id}{sha}; " + _BOTH_COMMANDS),
    "acceptance": ("приёмка — решение Оператора",
                   "проведи приёмку по критериям SPEC: artel.py approve {id}{sha} "
                   "или artel.py reject {id} \"причина\"; " + _BOTH_COMMANDS),
    "merge_gate": ("гейт merge — решение Оператора",
                   "artel.py approve {id}{sha}  (выполнит merge); " + _BOTH_COMMANDS),
    "escalated": ("эскалация — нужен Оператор",
                  "разберись: artel.py log {id}, затем artel.py approve {id}{sha}; "
                  + _BOTH_COMMANDS),
    "done": ("задача закрыта", "ничего не требуется"),
    "killed": ("задача снята", "ничего не требуется"),
}

# Эскалаций по существу две, и команда у них разная. Самая частая внутри цикла —
# исчерпанный потолок (enforce_budget); approve там увёл бы Оператора по кругу:
# задача вернулась бы в работу, а следующий run снова отказался бы стартовать.
AUTO_STOP_BUDGET = ("эскалация по бюджету — нужен Оператор",
                    "подними потолок: artel.py budget {id} <usd>  "
                    "(или artel.py kill {id})")

# Завершённый красный CI в `verifying` (SPEC T086, требование 2, AC-4):
# `auto` останавливает цикл сам, не дожидаясь потолка времени — verifying
# сам не возвращает задачу в разработку (ADR-0009, «Последствия»), только
# Оператор через `reject`.
AUTO_STOP_VERIFYING_RED = ("CI ветки красный — решение Оператора",
                          "artel.py reject {id} \"причина\"  (вернуть в "
                          "разработку)")

# Штатная пауза (SPEC T070, требование 2): `run` отказывается стартовать
# через тот же `sys.exit`, что и бюджет/лимит параллельных задач, поэтому
# нужна отдельная подсказка — "run отказался стартовать" не называет
# настоящую причину и не подсказывает `resume`.
AUTO_STOP_PAUSE = ("задача на паузе",
                   "artel.py resume {id} снимет пометку")

# Занятость зоны на старте кода (SPEC 01M1P9QAG65GVF69YJEV0V18D9,
# требования 3-4): причина внешняя (держит другая задача, не эта), тем же
# `sys.exit`, что и бюджет/лимит параллельных задач/пауза выше — реальную
# причину и держателя называет уже сам текст отказа `zone_lock.refusal`,
# здесь только литеральное «ждёт зоны» (auto-тест ищет её буквально) и
# подсказка на явное снятие Оператором.
AUTO_STOP_ZONE_WAIT = ("ждёт зоны",
                      "artel.py status  (кто держит зону) — дождись мержа/"
                      "kill занявшей задачи либо artel.py zone-release {id}; "
                      + _BOTH_COMMANDS)

# Штатное ожидание зоны внутри `auto` (SPEC 01M1VBEAWZW4EBZHKMGNBBK648,
# требования 1, 3): `--wait-zone` (либо этот дефолт для ВСЕХ вызовов,
# требование 1/AC-5) переключает отказ `AUTO_STOP_ZONE_WAIT` с
# немедленной остановки на цикл ожидания. `False` — сегодняшнее
# поведение (немедленная остановка) не меняется, пока Оператор явно не
# включит настройку — ни один существующий вызов `auto` без флага не
# затронут (AC-5).
AUTO_WAIT_ZONE_DEFAULT = False
# Интервал опроса `zone_lock.blocking_conflict` внутри цикла ожидания —
# по аналогии с `VERIFYING_POLL_INTERVAL_SEC` (тот же порядок величины,
# тот же довод: не насиловать БД частым опросом, но и не заставлять
# Оператора ждать заметно дольше освобождения зоны, чем нужно).
ZONE_WAIT_POLL_SEC = 90
# Потолок суммарного времени ожидания зоны (требование 3, AC-4/AC-8б):
# держатель может идти собственным путём через review/verifying/
# acceptance/merge_gate часами — потолок с запасом над этим, но не
# бесконечный: истечение останавливает цикл именованной причиной
# (задача остаётся `in_dev`, не эскалирует) вместо того, чтобы `auto`
# висел процессом сутками без надзора Оператора.
ZONE_WAIT_MAX_SEC = 6 * 3600

