"""Базовый интерфейс провайдера исполнителя роли (SPEC
01M2ZNTHSNFYSTF904P6SZTPYF, требование 1).

Один адрес на весь пульт для ответа «что нужно исполнителю роли»:
команда шага, окружение процесса, курируемый дом роли, предполётные
проверки, инструмент манифеста и вердикт совместимости модели с
установленным CLI. До этой задачи знание было размазано литералами по
`orchestrator/runner.py`, `orchestrator/stack.py`, `orchestrator/doctor/`
и `orchestrator/catalog.py`; запуск роли на другом CLI начинается с
того, чтобы собрать его сюда.

Модуль держится ЗАВЕДОМО 3.9-совместимым и на уровне модуля не
импортирует ничего, кроме стандартной библиотеки: `orchestrator/stack.py`
собирает `REQUIRED_TOOLS` обращением к реестру провайдеров, а сам
`stack.py` читается точкой входа `orchestrator/artel.py` ДО проверки
версии интерпретатора (SPEC 01M1SHK3MD4ZF9NYXSCT67J8AP, требование 2).
Отсюда же запрет на аннотации вида `X | None` в этом пакете: в 3.9 они
падают TypeError уже при объявлении функции.
"""
from collections import namedtuple

# Инструмент манифеста, объявленный самим провайдером: имя, минимальная
# версия кортежем и команда её проверки. `orchestrator/stack.py`
# переводит это в свою запись `ToolRequirement` — форму манифеста знает
# манифест, а значения знает провайдер.
CliTool = namedtuple("CliTool", "name minimum command")

# Курируемый дом роли: каталог референса в репозитории и имя, под
# которым он разворачивается в `.artel/home` (для `claude` — `claude` ->
# `.claude`, переименование при развёртывании, docs/reference/role-home.md).
HomeReference = namedtuple("HomeReference", "reference deployed_name")

# --- событие общего вида: то, что исполнитель ОТДАЁТ (SPEC
#     01M31ZHSA6HMH40C2JTDPQJQNZ, требование 1)
#
# Формат строки вывода знает провайдер; пульт знает только эти пять
# предметов. Namedtuple'ы стоят на уровне модуля, а не полями класса:
# `RoleExecutorProvider` объявляет КОНТРАКТ (что провайдер умеет), а
# форма события — общий словарь имён, которым пользуются обе стороны.

# Вызов инструмента: идентификатор (по нему вызов связывается со своим
# результатом), имя инструмента и ключевой аргумент — то немногое, что
# отличает повтор идентичного вызова от нового (метрика трения шага).
ToolCall = namedtuple("ToolCall", "id name argument")

# Результат вызова: идентификатор ТОГО вызова, текст результата и
# признак ошибки.
ToolResult = namedtuple("ToolResult", "call_id text is_error")

# Итог запуска (требование 1, AC-3): разбивка токенов по общим видам,
# стоимость в долларах от CLI ЛИБО её ОТСУТСТВИЕ (`usd is None` —
# отличимо от бесплатного запуска с `usd == 0.0`: по этому различию
# ветвится учёт стоимости, SPEC требование 4), признак ошибки и текст
# итога (у провала — текст ошибки, у успеха — текст результата: в
# потоке это одно поле).
RunResult = namedtuple("RunResult", "tokens_by_type usd is_error text")

# Одна строка вывода исполнителя как событие общего вида:
#
# - `log_text` — готовая строка лога шага («что показать Оператору»),
#   пустая для служебного события. Формат строки знает провайдер: и
#   отметка вызова инструмента, и сквозной проброс строки, не
#   разобравшейся в событие (stderr, трейсбек CLI), — его знание, а не
#   общее;
# - `text` — текст, который исполнитель сказал словами (`None` — не
#   говорил);
# - `tool_calls` / `tool_results` — кортежи `ToolCall`/`ToolResult`:
#   ОТДЕЛЬНЫМИ полями, потому что метрике трения шага нужны вызов и его
#   результат вместе, а лог результаты инструментов, наоборот, гасит;
# - `tokens_by_type` — учёт токенов ЭТОГО события разбивкой по четырём
#   общим видам `models.PRICE_KINDS` (`None` — события учёта не было;
#   пустая разбивка и её отсутствие — разные утверждения);
# - `run_result` — `RunResult` либо `None`, если это не итог запуска.
StreamEvent = namedtuple(
    "StreamEvent",
    "log_text text tool_calls tool_results tokens_by_type run_result")

# Сигнатуры одного класса провала: имя класса — ОБЩЕЕ
# (`orchestrator/failure_classification.py`), тексты — провайдерские.
FailureSignature = namedtuple("FailureSignature", "failure_class signatures")

#: Событие, в котором нет ничего: служебная строка, которую провайдер
#: разобрал и которой пульту сказать нечего.
EMPTY_EVENT = StreamEvent("", None, (), (), None, None)


class RoleExecutorProvider(object):
    """Интерфейс исполнителя роли. Реализация — на провайдера.

    Шесть методов требования 1 (`command`, `environment`,
    `home_reference`, `preflight`, `cli_tool`, `model_verdict`) —
    контракт, которым пользуется пульт. Ниже них — составные части
    предполёта: `preflight()` отдаёт ВЕСЬ набор проверок провайдера
    (его читает `doctor.all_checks` по каждой agent-роли), а пошаговый
    предполёт (`doctor.preflight_checks`) собирает из тех же частей
    свой порядок, перемежая их общими проверками пульта (диск, layout
    target'а, git-идентичность). Тела самих проверок живут в
    `orchestrator/doctor/preflight.py` — провайдер объявляет их состав и
    порядок, а не переписывает их заново.
    """

    #: Имя провайдера в реестре (`orchestrator/providers/__init__.py`).
    name = ""

    def command(self, model=None):
        """Argv шага роли. `model` — идентификатор модели роли либо
        `None` (дефолт CLI): аргумент, а не поле объекта, потому что
        модель у каждой роли своя, а провайдер один на пульт."""
        raise NotImplementedError

    def environment(self, role=None, task_id=None):
        """Провайдерская часть окружения процесса роли (дом, конфиг,
        секрет) — словарь ПОВЕРХ общего белого списка манифеста, который
        собирает `runner.role_env`. PATH, метки роли/задачи и
        git-идентичность остаются общими и сюда не входят."""
        raise NotImplementedError

    def home_reference(self):
        """`HomeReference` курируемого дома роли."""
        raise NotImplementedError

    def preflight(self, role):
        """Предполётные проверки провайдера списком `doctor.Check`: CLI
        найден, версия CLI, секрет роли, дом роли."""
        raise NotImplementedError

    def cli_tool(self):
        """`CliTool` — инструмент манифеста стека и его минимальная
        версия."""
        raise NotImplementedError

    def model_verdict(self, model):
        """Вердикт совместимости модели с УСТАНОВЛЕННЫМ CLI
        (`stack.ModelCliVerdict`): `ok`/`warn`/`fail`.

        Минимум версии CLI у модели берётся из каталога `models.yaml`
        (`models.catalog_model`), а не из таблицы внутри провайдера:
        таблица `stack.MODEL_MIN_CLI_VERSION` удалена вместе со своим
        предупреждением (SPEC 01M3009Y9AGGY6ZCFA7H1HJ1TD, требование
        10). Модель, которой в каталоге нет, — `fail`, а НЕ `warn`: это
        и есть fail-closed, ради которого таблица переезжала, и второй
        провайдер обязан вести себя так же. Решение о том, стоит ли
        ради вердикта спрашивать версию CLI подпроцессом, остаётся за
        провайдером — ради заведомого отказа не стоит.
        """
        raise NotImplementedError

    # --- составные части preflight() -----------------------------------

    def check_cli_found(self):
        """Проверка «CLI найден» (блокирующая)."""
        raise NotImplementedError

    def check_cli_version(self):
        """Проверка «версия CLI» (предупреждение, не блок)."""
        raise NotImplementedError

    def check_token(self, role):
        """Проверка «секрет роли добыт» (блокирующая)."""
        raise NotImplementedError

    def check_home_reference(self):
        """Сверка развёрнутого дома роли с референсом провайдера."""
        raise NotImplementedError

    # --- прочее ---------------------------------------------------------

    def installed_cli_version(self):
        """Установленная версия CLI кортежем; `None` — не определилась."""
        raise NotImplementedError

    def live_smoke_command(self, prompt):
        """Argv минимального живого вызова CLI (`doctor.live_smoke`):
        тот же инструмент, что реально исполняет шаг, но без рабочей
        обвязки шага."""
        raise NotImplementedError

    # --- то, что исполнитель ОТДАЁТ (SPEC 01M31ZHSA6HMH40C2JTDPQJQNZ) ----

    def parse_output_line(self, raw_line):
        """Одна строка вывода исполнителя -> `StreamEvent` (требование 1).

        Разбор ВСЕГДА отдаёт событие, даже на строке, которая ни во что
        не разобралась: пульт не вправе молча глотать вывод шага, а
        решение «эта строка — мусор» принимает тот, кто знает формат.
        Строка не относится ни к одному из пяти предметов — `EMPTY_EVENT`.

        Тела не несёт намеренно: провайдер, забывший реализовать разбор,
        обязан отказать громко, а не отдать шаг без лога, без трения и
        без стоимости.
        """
        raise NotImplementedError

    def failure_signatures(self):
        """Сигнатуры провалов попытки: кортеж `FailureSignature` В
        ПОРЯДКЕ ПРОВЕРКИ (SPEC 01M31ZHSA6HMH40C2JTDPQJQNZ, требование 9).

        Порядок — часть данных, а не кода классификатора: специфичные
        списки обязаны перехватывать текст раньше общего якоря своего
        CLI, иначе детерминированный отказ уходит в повторы с бэкоффом.
        Имена классов и их последствия общие
        (`orchestrator/failure_classification.py`) — провайдер отвечает
        только за тексты, которыми ЕГО CLI об этих классах сообщает.
        """
        raise NotImplementedError

    def required_cli_version(self, text):
        """Версия CLI, которую текст провалившейся попытки называет
        минимальной; `None` — текст её не несёт. Формулировка — своя у
        каждого CLI, поэтому извлечение здесь, а не в общем модуле."""
        raise NotImplementedError
