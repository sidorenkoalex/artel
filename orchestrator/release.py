"""Команда `release`: операторское снятие lease задачи (SPEC T062).

Прецеденты T046, T051, T060: застрявший lease блокирует мутирующие
команды на весь `LEASE_STALE_AFTER_SEC`, а с лимитером параллельных
задач (T060, инвариант 32) занимает ещё и слот лимитера — до этой
задачи снять его можно было только прямой записью в БД руками.

`cmd_release` не берёт lease задачи сама и не проходит проверку
лимитера (требование 4, AC-5): она не мутирующая команда в смысле
`lease.run_locked` — ей нечего продлевать или перехватывать, только
прочитать и удалить чужую строку `leases`, поэтому `lease.acquire`/
`lease.run_locked`/`parallel_limit.refusal` здесь не вызываются вовсе.
Свежесть lease не проверяется перед снятием (требование 2): решение
снять живой замок — на совести Оператора, не на пульте — но `cmd_release`
(SPEC 01M1NEEYSP0QWPMXHG0BK591M7) теперь предупреждает о нём ДО снятия,
если он ЖИВОЙ и принадлежит другой сессии (`lease.warn_foreign_live`):
предупреждение только информирует, снятие не блокирует и подтверждения
не запрашивает.
"""
from . import lease, liveness, store
from .session import resolve_session_id


def cmd_release(task_id: str) -> None:
    """Снимает lease задачи, если он есть, и журналирует данные бывшего
    держателя (`session_id`, `pid`, `hostname`, возраст heartbeat).

    Задача без lease — не ошибка (требование 3): печатает дружелюбное
    сообщение и обычным `return` завершается кодом возврата 0. Журнал в
    этом случае не пишется — решению разработчика (AC-3): запись о
    снятии несуществующей строки не несла бы новой информации, которую
    не несёт уже сам факт отсутствия lease у задачи.

    Префикс -> полный id (SPEC T094, требование 3, AC-3) резолвится ЗДЕСЬ,
    до чтения `leases` (REVIEW T094 итерация 1, замечание 1).

    Предупреждение о чужом живом lease (SPEC 01M1NEEYSP0QWPMXHG0BK591M7,
    требование 1) печатается ЗДЕСЬ же, до веток "нет lease"/снятия —
    верно независимо от того, окажется ли сам `release` no-op'ом под
    гонкой ниже.
    """
    conn = store.db()
    task_id = store.resolve_task_id(conn, task_id)
    lease.warn_foreign_live(conn, task_id, resolve_session_id())
    row = store.lease_row(conn, task_id)
    if row is None:
        print(f"[{task_id}] lease не заведён — снимать нечего")
        return
    age = int(liveness._age_seconds(row["heartbeat_ts"]))
    detail = (f"session_id={row['session_id']}, pid={row['pid']}, "
             f"hostname={row['hostname']}, heartbeat {age} сек назад")
    # `release_lease` сносит строку, только если session_id совпадает с
    # только что прочитанным — строка не поменялась своим держателем между
    # чтением и сносом (перехват другой сессией между `lease_row` и этим
    # вызовом), безопаснее голого удаления по одному task_id: не заденет
    # чужую строку, вставленную уже после нашего чтения. Возврат `False`
    # значит ровно это — строка сменила держателя раньше нас, физически
    # ничего не снято, поэтому журнал и печать не имеют права заявлять
    # успех с данными устаревшего чтения (REVIEW T062, итерация 1,
    # Замечание 1): вместо этого — правдивое сообщение о гонке.
    removed = store.release_lease(conn, task_id, row["session_id"])
    if not removed:
        note = (f"lease уже сменил держателя — Оператор снял устаревшее "
               f"чтение ({detail}), фактического снятия не произошло")
        print(f"[{task_id}] {note}")
        return
    store.journal(conn, task_id, "operator", "lease снят Оператором", detail)
    print(f"[{task_id}] lease снят Оператором: {detail}")
