"""Идентификатор сессии оркестратора — единая функция для всех команд
(SPEC 01M1GCHKG8DDK4DCZWCE3DYKWC, требование 1, AC-1).

Раньше жила только в `orchestrator/lease.py` (SPEC T044) и была доступна
лишь мутирующим командам, уже проходящим через lease-обвязку
(`lease.run_locked`). Вынесена сюда отдельным листом графа импортов
(только stdlib, тем же приёмом, что и `orchestrator/liveness.py`), чтобы
любой модуль — включая `orchestrator/store.py::journal` — мог резолвить
identity вызывающей сессии ТЕМ ЖЕ источником, каким её резолвит lease, а
не собственным (и потому способным разойтись) чтением
`ARTEL_SESSION_ID`. `lease.resolve_session_id` остаётся тем же самым
объектом функции (`from .session import resolve_session_id`), не второй
копией — правка источника identity здесь одинаково видна под обоими
именами.
"""
import os


def resolve_session_id(session_id: str | None = None) -> str:
    """Identity вызывающей сессии.

    Источник по умолчанию SPEC не фиксирует (SPEC T044, требование 9):
    `ARTEL_SESSION_ID` из окружения, если задан явно, иначе pid
    родительского процесса. Один терминал/шелл — один родительский pid
    на всё время жизни сессии, то есть последовательные вызовы CLI из
    одного терминала получают одну и ту же identity без всякой
    настройки; два разных терминала получают разные pid. Явный параметр
    (тестовый шов приёмочных тестов) всегда сильнее обоих источников
    окружения.
    """
    if session_id:
        return session_id
    return os.environ.get("ARTEL_SESSION_ID") or f"ppid-{os.getppid()}"
